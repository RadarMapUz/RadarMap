//
//  Геометрия кадра карты: где на экране «я», где тревожная камера и какую
//  долю высоты забирают панели поверх карты.
//
//  Здесь — то, что пережило схему дороги (RoadSketch, удалена 11.10 вместе с
//  приборкой; её геометрия вычищена 19.10): движок карты и CarPlay стоят на
//  тех же полях и долях, и они проверены тестами кадра (MapFrameStateTests,
//  CarPlayEngineTests, DriveCameraTests).
//

import Foundation

nonisolated enum MapViewport {

    /// Где стоит «я»: не в центре, а ниже — впереди должно быть видно больше,
    /// чем позади. Тот же приём, что у любого навигатора.
    ///
    /// Доля ВИДИМОЙ части вида, а не всего экрана: панели поверх карты
    /// забирают себе четверть высоты, и считать от неё — значит ставить «я» и
    /// камеру не туда, где на них смотрят (см. Insets).
    static let meY: Double = AppConfig.mapMeY

    /// Где стоит тревожная камера, когда охват выбирается по ней. Доля
    /// видимой части сверху: 15 %, а не 12 % экрана, — иначе камера
    /// рисовалась под карточкой скорости (снимок живой поездки: «344 м до
    /// камеры» в карточке — и ни одной камеры на карте).
    static let cameraTopShare: Double = 0.15

    /// Насколько близко к верхней кромке видимого камера ещё считается
    /// попавшей в охват. Ниже этого она была бы наполовину за краем.
    static let cameraEdgeShare: Double = 0.05

    /// Поля вида: какую долю высоты забирают панели поверх карты.
    ///
    /// Карта лежит во весь экран, а видно из неё не всё: сверху карточка
    /// скорости и объявления, снизу панель поездки (и карточка камеры в
    /// навигации). Проекция считается от ВИДИМОГО прямоугольника. Хост
    /// измеряет свои панели сам (MapFrameState); CarPlay оставляет поля
    /// пустыми — там карта ничем не закрыта.
    struct Insets: Equatable, Sendable {
        var top: Double = 0
        var bottom: Double = 0

        static let none = Insets()

        /// Потолок полей. Панель, забравшая больше двух третей экрана, — это
        /// уже не карта с панелью, и геометрия не обязана считать такой
        /// случай осмысленным; она обязана не сойти с ума.
        var safeTop: Double { min(max(0, top), 0.45) }
        var safeBottom: Double { min(max(0, bottom), 0.35) }

        /// Доля высоты, которая видна.
        var visible: Double { max(0.35, 1 - safeTop - safeBottom) }

        /// Где стоит «я» — доля ПОЛНОЙ высоты вида.
        var meY: Double { safeTop + visible * MapViewport.meY }
        /// Куда охват ставит тревожную камеру — доля полной высоты.
        var cameraY: Double { safeTop + visible * MapViewport.cameraTopShare }
        /// Верхняя кромка, за которую камера уже не считается видимой.
        var cameraEdgeY: Double { safeTop + visible * MapViewport.cameraEdgeShare }
    }

    /// Сдвиг меньше шума GPS на стоянке: прогресс маршрута не пересчитывается
    /// (чуть выше типичного дрожания хорошего фикса, ±1 м).
    static let standstillMeters = 2.0

    /// Охваты, на которых видны объекты тайлов дорог (SketchArea/Point/Place
    /// — разбор файлов тайлов): улицы до 340 м, дальше костяк района;
    /// точечные объекты — до 700 м.
    static let farNetworkSpan: Double = 340
    static let maxSpanMeters: Double = 700
}
