//  «Превышаем устойчиво» — с какого момента, если лимит стал известен только что.
//
//  Устойчивость (`isOverspeedingSustained`) — то, что поднимает фразу о
//  камере до срочной. Раньше она мерилась от момента, когда превышение
//  ВПЕРВЫЕ стало видно, и тик без лимита обнулял отсчёт. На дороге без
//  `maxspeed` в OSM лимит предполагается по классу дороги ближайшей камеры
//  (`RoadClass.assumedLimitKmh`), а ближайшая камера появляется ровно на тике
//  первого оповещения о ней. Значит, на этом тике отсчёт только начинался, и
//  первая фраза на 100 в зоне 70 выходила спокойной (прогон трассы 13.3).
//  Одного порядка тика (лимит считается ДО оповещения, см. handleLocationBody)
//  мало: лимит на этом тике только появился, и отсчёт с нуля не успевал.
//
//  Здесь отсчёт идёт по самой скорости. Тик с ИЗВЕСТНЫМ лимитом судится своим
//  вердиктом, как раньше: если лимит прыгнул (сегмент соседней улицы с 40 на
//  один тик), прошлые тики были «в лимите» — и отсчёт честно начинается
//  заново, защита от такого скачка остаётся. Тик БЕЗ лимита — не «в лимите»,
//  а «неизвестно»: его скорость судится по лимиту, который известен сейчас.
//  Ошибка в эту сторону — срочная фраза на камере, о которой и так говорим;
//  это безопасная сторона.
//
//  Чистая логика — покрыта OverspeedRunTests.
//

import Foundation

nonisolated struct OverspeedRun {

    struct Sample: Equatable {
        let at: Date
        let kmh: Double
        /// Вердикт по лимиту, известному НА ЭТОМ тике; nil — лимита не было.
        let over: Bool?
    }

    private(set) var samples: [Sample] = []

    /// Тик GPS: скорость и вердикт по лимиту этого тика (nil — лимит неизвестен).
    /// Хранятся последние `AppConfig.overspeedRunSamples` тиков — по числу, а не
    /// по времени: в кармане фиксы приходят раз в несколько секунд, и окно по
    /// времени теряло бы прошлый тик целиком.
    mutating func note(kmh: Double, over: Bool?, at now: Date) {
        samples.append(Sample(at: now, kmh: kmh, over: over))
        if samples.count > AppConfig.overspeedRunSamples { samples.removeFirst() }
    }

    /// С какого момента превышение НЕПРЕРЫВНО — по последним тикам назад, пока
    /// они «над»: тики с известным лимитом — своим вердиктом, без лимита —
    /// скоростью против `line` (лимит + порог текущего тика). nil — сейчас не
    /// превышаем. Отсчёт длиннее окна упирается в старейший тик — для
    /// секундных порогов этого достаточно с запасом.
    func since(line: Double) -> Date? {
        var start: Date?
        for sample in samples.reversed() {
            guard sample.over ?? (sample.kmh > line) else { break }
            start = sample.at
        }
        return start
    }

    /// Превышение держится не меньше `seconds`.
    func isSustained(line: Double, seconds: TimeInterval, now: Date) -> Bool {
        since(line: line).map { now.timeIntervalSince($0) >= seconds } ?? false
    }

    mutating func reset() {
        samples.removeAll()
    }
}
