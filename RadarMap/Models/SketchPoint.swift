//
//  SketchPoint.swift
//  RadarMap
//
//  Точечные объекты схемы: светофор, лежачий полицейский, стоп-линия, разворот.
//
//  Это ПЕРВЫЙ слой, который приходит не из OSM, а нарисован руками в панели.
//  Отсюда два правила, которых нет у остального:
//
//  • Такие данные не с чем сверить. Дорогу можно сравнить с чужой картой, а
//    светофор, поставленный человеком, подтверждается только этим человеком.
//    Поэтому вид объекта, которого приложение не знает, НЕ рисуется — но и не
//    роняет тайл: сервер вправе завести новый вид раньше, чем выйдет сборка.
//
//  • Виден такой объект только вблизи. На охвате района светофор — точка в
//    один пиксель среди сотни таких же, то есть шум; на ближнем плане это
//    ориентир, по которому водитель понимает, где он.
//

import CoreLocation

nonisolated struct SketchPoint: Sendable {

    /// Коды — контракт с build_roads.py (POINT_TRAFFIC_LIGHT и соседние).
    enum Kind: Int, Sendable, CaseIterable {
        case trafficLight = 1
        case speedBump = 2
        case stopLine = 3
        case uTurn = 4
        /// Пешеходный переход. Не значок, а КРАСКА — см. `isPaint`.
        case crossing = 5
        /// Стрелки полос перед перекрёстком. Тоже краска: по стрелке на полосу,
        /// каждая повёрнута по своему направлению.
        case laneArrows = 6

        /// До какого охвата объект имеет смысл.
        ///
        /// Граница НЕ на вкус, а по геометрии: дальше farNetworkSpan схема
        /// рисует не улицы, а костяк района — раздельные проезжие части там
        /// сведены в одну ось, то есть линия проходит МЕЖДУ ними. Точка
        /// посажена сервером на детальную геометрию, и на костяке она уехала
        /// бы от нарисованной дороги на полширины проспекта.
        ///
        /// Плотность на этой границе замерена: в самом плотном кадре центра
        /// Ташкента 7 пиктограмм на охвате 260 м и 9 на 340 — то есть предел
        /// ставит геометрия, а не теснота.
        ///
        /// Светофор — исключение: для него сервер считает ВТОРОЙ набор, по
        /// костяку района, поэтому он живёт до самого дальнего охвата. Так и
        /// надо: на охвате района светофоры — это и есть карта перекрёстков,
        /// по ней читается, где город, а где проезд насквозь.
        var maxSpanMeters: Double {
            switch self {
            case .trafficLight: return MapViewport.maxSpanMeters
            // Краска мельче значка на порядок: дальше сотни метров зебра —
            // это пиксель, а стоп-линия и вовсе волос. Решение по ним
            // принимают на подъезде, и раньше они не нужны.
            case .crossing: return 120
            case .stopLine: return 150
            // Решение о полосе принимают здесь и сейчас: дальше ста метров
            // стрелка — пиксель, а перестроиться всё равно уже поздно.
            case .laneArrows: return 120
            default: return MapViewport.farNetworkSpan
            }
        }

        /// Краска на асфальте, а не значок над ним.
        ///
        /// Разница не косметическая, она определяет СЛОЙ. Значок едет отдельным
        /// слоем, которому возвращён курс, — иначе светофор ложится набок на
        /// повороте. Краска обязана поворачиваться ВМЕСТЕ с дорогой: зебра,
        /// которой вернули курс, встала бы поперёк собственного перехода.
        /// Поэтому краска живёт в растре, рядом с осевой и разделительными.
        var isPaint: Bool {
            self == .crossing || self == .stopLine || self == .laneArrows
        }

        /// Есть ли чем нарисовать вид, если краска не вышла.
        ///
        /// Стоп-линия жила пиктограммой до того, как у точки появились азимут
        /// и ширина, и обязана жить ею дальше там, где сервер дороги под точкой
        /// не нашёл: иначе объект, который раньше было видно, просто исчезнет.
        /// У зебры запасного варианта нет — значка для неё не существует.
        var hasGlyph: Bool { self != .crossing && self != .laneArrows }
    }

    var coordinate: CLLocationCoordinate2D
    var kind: Kind
    /// Азимут дороги под точкой, градусы. Краска чертится ПОПЕРЁК него.
    var azimuthDegrees: Double = 0
    /// Ширина проезжей части под точкой, метры. 0 — сервер не измерил, и
    /// чертить нечем.
    var widthMeters: Double = 0
    /// Куда можно с каждой полосы, слева направо. Пусто у всего, кроме стрелок.
    var turns: [LaneTurn] = []
}

/// Направление полосы. Коды — контракт с build_roads.py (TURN_THROUGH и
/// соседние). Неизвестный код читается как `.none`, а не роняет запись: в
/// turn:lanes встречается что угодно, и терять из-за этого дорогу нельзя.
nonisolated enum LaneTurn: Int, Sendable, CaseIterable {
    case none = 0
    case through = 1
    case left = 2
    case right = 3
    case slightLeft = 4
    case slightRight = 5
    case uTurn = 6
    case throughLeft = 7
    case throughRight = 8
    case leftRight = 9

    /// Углы стрелок относительно хода дороги, градусы. Их может быть два —
    /// «прямо и налево» рисуется двумя стрелками из одной точки, а не одной
    /// двусмысленной.
    var angles: [Double] {
        switch self {
        case .none:         return []
        case .through:      return [0]
        case .left:         return [-90]
        case .right:        return [90]
        case .slightLeft:   return [-35]
        case .slightRight:  return [35]
        case .uTurn:        return [-160]
        case .throughLeft:  return [0, -90]
        case .throughRight: return [0, 90]
        case .leftRight:    return [-90, 90]
        }
    }
}

extension SketchPoint: Equatable {
    static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.kind == rhs.kind
            && lhs.coordinate.latitude == rhs.coordinate.latitude
            && lhs.coordinate.longitude == rhs.coordinate.longitude
            && lhs.azimuthDegrees == rhs.azimuthDegrees
            && lhs.widthMeters == rhs.widthMeters
            && lhs.turns == rhs.turns
    }
}
