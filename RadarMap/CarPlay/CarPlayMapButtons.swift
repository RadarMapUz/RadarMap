//  Какие кнопки карты стоят в машине — по состоянию экрана.
//
//  Владелец 21.10: «камеру/радар нужно же отмечать». В баре «Радар!» — одна
//  кнопка из четырёх, мелкая капсула в углу; на ходу по ней промахиваются.
//  Кнопки карты крупнее и стоят столбиком у края, куда рука идёт вслепую, —
//  поэтому в поездке первая из них — «Радар!» (план 25.H3).
//
//  Мест у кнопок карты четыре (`CPMapTemplate.mapButtons`: «will only display
//  the first 4 buttons»), в осмотре система оставляет две и прячет лишние с
//  конца. Набор в поездке — «Радар!», +, −, и четвёртое место делят «осмотр»
//  и «к себе» по состоянию карты:
//   • карта за машиной — «к себе» ничего не сделает, место отдано осмотру;
//   • водитель сдвинул карту (палец, «Весь маршрут», выход из осмотра) —
//     нужен путь назад, и на месте осмотра стоит «к себе».
//  Состояние слежения по-прежнему видно: само появление «к себе» и есть
//  «карта ушла от машины». «+ −» остаются: зум в поездке ведёт
//  DriveCamera, но поправку водителя (`zoomBias`) убирать нельзя, а одна
//  кнопка зума без пары — загадка. Осмотр обязателен (на машинах без
//  сенсора крутилкой двигают карту только из него) — он остаётся в один тап,
//  когда карта за машиной, и в два («к себе», потом осмотр), когда нет.
//
//  Без поездки — прежний набор: +, −, осмотр, «к себе». На выборе маршрута —
//  тоже прежний: машина стоит, отмечать нечего, а «+ −» там нужны (аудит
//  18.10, п. 9).
//
//  Чистая логика без UIKit; покрыто CarPlayMapButtonsTests.
//

import Foundation

nonisolated enum CarPlayMapButtons {

    enum Kind: Hashable, Sendable {
        /// «Отметить» — выбор типа баннером, тренога сама через 3 с (`beginReport`).
        case report
        case zoomIn
        case zoomOut
        /// Вход в осмотр (панорамирование).
        case pan
        /// «К себе»: залитый значок — карта за машиной, контурный — нет.
        case recenter(following: Bool)
    }

    /// Сколько кнопок карты показывает шаблон (CPMapTemplate.h).
    static let limit = 4
    /// Сколько их остаётся видно в осмотре (showPanningInterface).
    static let panningLimit = 2

    /// Кнопки карты сверху вниз. Порядок — и порядок фокуса крутилки:
    /// «Радар!» первой достаётся одним поворотом.
    static func layout(tripActive: Bool, following: Bool,
                       panning: Bool, previewing: Bool) -> [Kind] {
        // В осмотре — ровно зум: система всё равно спрячет лишнее с конца,
        // а выход — «Готово» в баре.
        if panning { return [.zoomIn, .zoomOut] }
        guard tripActive, !previewing else {
            return [.zoomIn, .zoomOut, .pan, .recenter(following: following)]
        }
        return [.report, .zoomIn, .zoomOut, following ? .pan : .recenter(following: false)]
    }
}
