    static let familyNoticeSeconds: Double = 6

    // MARK: - Маршрут без сети (OfflineRouteGraph, 12б.10)

    /// Точка дальше этого от междугородней дороги — офлайн-маршрута нет:
    /// улиц города в этапе 1 нет, и прямая через квартал была бы враньём.
    static let offlineRouteSnapMeters = 3_000.0
    /// Съезд с маршрута без сети — только дальше этого от его линии. Подъезд
