//
//  NavigationFlow.swift
//  RadarMap
//
//  Одна таблица переходов «маршрут ↔ поездка» для телефона и машины.
//
//  Маршрут и поездка у нас — две независимые вещи (RouteService и
//  LocationService), и каждый экран сам решал, что показать из их пары.
//  Телефон решал правильно: маршрут без поездки — это ВЫБОР («Поехали» /
//  крестик), маршрут с поездкой — ВЕДЕНИЕ. Машина смотрела только на
//  маршрут и вела всегда, когда он есть. Отсюда два случая 12.10:
//    * «Стоп» в машине: тост «Поездка завершена», кнопка ▶ — и при этом
//      карточка «Поверните налево», прибытие, стрелки: маршрут остался, и
//      машина продолжала по нему вести;
//    * на телефоне выбор «улица Беруни, 30а — Поехали», а на главном экране
//      машины — «40 м, поверните налево» и ETA.
//
//  Здесь — три фазы, общие для обоих экранов, и правила переходов:
//    * свободно (маршрута нет) — поездка может идти, ведения нет;
//    * выбор (маршрут есть, поездки нет) — телефон: панель «Поехали»;
//      машина: выбор маршрута CarPlay (CPTrip) с той же кнопкой;
//    * ведение (маршрут и поездка) — телефон: манёвр; машина: сессия.
//  «Стоп» рукой — конец маршрута на любом экране (как «Завершить» в Apple
//  Maps и Яндексе): иначе стоп на одном экране оставлял выбор с «Поехали»
//  на другом. Автостоп (CoreMotion, долгая стоянка в пути) и «я пассажир»
//  маршрут оставляют: тронулись — автостарт вернёт ведение к той же цели.
//
//  Чистая логика; NavigationFlowTests.
//

import Foundation

nonisolated enum NavigationFlow {

    enum Phase: Equatable, Sendable {
        /// Маршрута нет.
        case free
        /// Маршрут построен, поездка не идёт: ждём «Поехали».
        case choosing
        /// Едем по маршруту.
        case guiding
    }

    static func phase(hasRoute: Bool, isTripActive: Bool) -> Phase {
        guard hasRoute else { return .free }
        return isTripActive ? .guiding : .choosing
    }

    /// Кто закончил поездку.
    enum TripEnd: Equatable, Sendable {
        /// Кнопка «Стоп» / «Завершить» (телефон, машина, Siri).
        case manual
        /// Автостоп по CoreMotion — человек ничего не решал.
        case auto
        /// «Я пассажир» — записи нет, но маршрут, возможно, нужен.
        case passenger
    }

    /// Остаётся ли маршрут после конца поездки.
    static func keepsRoute(after end: TripEnd) -> Bool {
        end != .manual
    }

    /// Что машине сделать со своим экраном выбора.
    enum CarChoice: Equatable, Sendable {
        case none
        /// Показать выбор маршрута, построенного не в машине (на телефоне)
        /// или оставшегося после автостопа.
        case show
        /// Закрыть: поехали (с телефона, автостартом) или маршрут сняли.
        case close
    }

    /// Решение — по ПЕРЕХОДУ фазы, а не по фазе: машина может сама держать
    /// выбор поверх идущей поездки (стоя на светофоре, выбирает новый путь),
    /// и фаза «ведение» в эти секунды не повод выбор закрывать.
    /// - Parameters:
    ///   - previous: фаза при прошлом решении; nil — машина только что
    ///     подключилась.
    ///   - showing: выбор уже на экране машины.
    ///   - building: машина сама строит маршрут — фаза в эти секунды
    ///     промежуточная (маршрут уже есть, поездки ещё нет), и показывать по
    ///     ней выбор значило бы перебить решение «едем сразу» на ходу.
    static func carChoice(from previous: Phase?, to phase: Phase,
                          showing: Bool, building: Bool) -> CarChoice {
        guard !building else { return .none }
        if showing {
            // Маршрут сняли (крестик на телефоне) — выбирать нечего.
            if phase == .free { return .close }
            // Поехали не из выбора машины: «Поехали» на телефоне, автостарт.
            if phase == .guiding, previous != .guiding { return .close }
            return .none
        }
        // Маршрут построен на телефоне, остался после автостопа или ждал,
        // пока машина подключится, — тот же выбор и в машине.
        if phase == .choosing, previous != .choosing { return .show }
        return .none
    }

    /// Вести ли машине (сессия CPNavigationSession, манёвр, ETA): только в
    /// ведении и не поверх выбора.
    static func carGuides(phase: Phase, choosing: Bool) -> Bool {
        phase == .guiding && !choosing
    }
}
