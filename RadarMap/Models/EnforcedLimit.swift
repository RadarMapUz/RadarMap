//
//  Лимит, по которому судят ДЕНЬГИ и РЕЙТИНГ, — не тот же, что показывает знак.
//
//  Замер боевого speed_limits.json в границах Ташкента: 13 707 сегментов, из
//  них 922 несут тег 50 и ещё около 1150 — 5, 20, 30 и 40. Пятнадцать
//  процентов городской сети утверждают, что ехать можно меньше 60. По ПДД РУз
//  в населённом пункте разрешено 70, а фиксация камерой начинается с 60, и
//  камеры на 50 в городе нет ни одной. То есть эти теги — дворовые проезды,
//  разметка и копипаста европейских дефолтов, а не знак, который стоит у
//  камеры.
//
//  Цена этой лжи не абстрактная: с тега 50 проезд на 66 км/ч превращался в
//  «превышение», 440 000 сум возможного штрафа и −8 к баллу поездки. Приложение
//  выставляло счёт за то, за что никто не штрафует.
//
//  Направление правки выбрано намеренно одностороннее, и это то самое правило
//  из docs/plan_algorithms.md §5: **поднимать лимит нельзя, снимать обвинение
//  можно**. Поэтому пол применяется РОВНО к записанному проезду — к деньгам,
//  баллу и надписи «превышение», — и не трогает живой лимит дороги
//  (SpeedLimitService.currentLimit): голос, HUD и знак на приборке продолжают
//  знать про 50 и продолжают о нём говорить. Совет остаётся, счёт уходит.
//
//  Чистое правило — покрыто EnforcedLimitTests.
//

import Foundation

nonisolated enum EnforcedLimit {
    /// Ниже этого камера не фиксирует. Одно число на всё приложение.
    static let floorKmh = 60

    /// Лимит для денег и рейтинга по лимиту дороги.
    static func kmh(road: Int) -> Int { max(road, floorKmh) }

    /// Тот же пол для необязательного лимита: `nil` остаётся `nil` — «лимита
    /// не было вовсе» и «лимит ниже пола» это разные вещи, и первую пол не
    /// вправе превращать во вторую.
    ///
    /// Имя ДРУГОЕ, а не вторая перегрузка `kmh(road:)`. Перегрузка по
    /// `Int`/`Int?` с одной и той же меткой неразрешима там, где результат
    /// кладут в `Int?`: оба варианта подходят, и компилятор честно ругается
    /// «ambiguous use». Место как раз такое — запись проезда.
    static func applied(to road: Int?) -> Int? {
        guard let road else { return nil }
        return max(road, floorKmh)
    }

    /// Пол реально сработал: знак на дороге ниже того, по чему считаем.
    /// Экран проезда говорит об этом вслух — мы не начинаем врать про знак,
    /// мы перестаём выставлять за него счёт.
    static func isFloored(road: Int?) -> Bool {
        guard let road else { return false }
        return road < floorKmh
    }
}
