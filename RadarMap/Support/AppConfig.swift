    /// На сколько должна измениться частота превышений на 100 км, чтобы назвать
    /// это трендом, а не шумом одной поездки.
    static let insightTrendChange = 0.3
    /// И минимальный абсолютный шаг: с 0,2 до 0,3 — рост в полтора раза по
