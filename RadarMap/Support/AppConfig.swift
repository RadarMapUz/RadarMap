    /// улицы к ней уходят вбок на сотни метров: при обычных 150 м каждое
    /// перестроение без сети давало ту же прямую от новой точки — по кругу,
    /// с «Маршрут перестроен» каждые полминуты (ревью 14.2). Не ту трассу
    /// это всё равно ловит: дороги расходятся на километры за минуты.
    static let offlineRouteRerouteMeters = offlineRouteSnapMeters
    /// Повтор замены маршрута без сети серверным — не чаще, с. Связь могла и
