//
//  MapMode.swift
//  RadarMap
//
//  Режим главного экрана — что водителю нужно прямо сейчас.
//
//  Экран рос наращиванием: каждая фича добавляла свой элемент поверх карты, а
//  видимость решалась россыпью `if` внутри одной вёрстки. В покое на карте
//  оказывалось девять элементов сразу (HUD, компас, локация, «радар здесь»,
//  легенда, Дом/Работа, «Начать поездку», бар действий, подсказка «похоже, вы
//  едете») — из них нужен один. Здесь правило «что показываем» становится
//  явным и проверяемым: режим один, набор элементов фиксирован.
//
//  Чистое перечисление без SwiftUI — покрыто тестами (MapModeTests).
//

import Foundation

nonisolated enum MapMode: Equatable {
    /// Стоим: поездки нет. Экран про «куда поедем».
    case idle
    /// Едем без маршрута. Экран про «что впереди».
    case driving
    /// Едем по маршруту. Экран про «куда поворачивать».
    case navigating

    static func current(isTripActive: Bool, hasRoute: Bool) -> MapMode {
        if isTripActive { return hasRoute ? .navigating : .driving }
        return .idle
    }

    // MARK: - Правила видимости
    //
    // Каждое свойство отвечает ровно на один вопрос и читается как чек-лист.
    // Добавляя элемент на экран, его место в этой таблице выбирается осознанно,
    // а не «ещё один if рядом с существующими».

    // Правила «какая подложка» здесь больше нет, и это главная правка экрана.
    //
    // Было: `allowsSketchMap = self != .idle` — то есть режим ПЕРЕБИВАЛ выбор
    // человека, и на стоянке своей карты не бывало вовсе. Включивший её видел
    // карту Apple и делал единственный возможный вывод: не работает.
    //
    // Стало: выбор живёт в настройках одним значением (MapBase), меняется
    // кнопкой на самой карте и действует немедленно в любом режиме. Режиму
    // остаётся то, что он и должен решать, — что показать ПОВЕРХ карты.

    /// Дом/Работа и «Начать поездку» — только в покое: в движении это шум.
    var showsQuickDestinations: Bool { self == .idle }

    /// Нижний бар действий (поиск, список камер, настройки, Итоги).
    var showsActionBar: Bool { self == .idle }

    // Легенды типов камер здесь тоже больше нет: она объясняет МАРКЕРЫ, а
    // маркеры зависят от подложки, а не от режима. На своей схеме и на
    // движке этих кружков не рисуют вовсе — значит и объяснять нечего.
    // Правило переехало в панель слоёв (MapLayersControl.showsLegend).

    /// Отметить радар одним тапом — смысл имеет только на ходу.
    var showsReportButton: Bool { self != .idle }

    /// Компактная строка поездки внизу (прибытие · остаток · камера · стоп).
    var showsTripBar: Bool { self != .idle }

    /// Баннер манёвра сверху.
    var showsManeuver: Bool { self == .navigating }

    /// Панель маршрута с вариантами — до старта поездки.
    var showsRoutePanel: Bool { self == .idle }

    /// Карта разворачивается по ходу движения и наклоняется.
    var followsHeading: Bool { self != .idle }

    /// Слои, 3D, «весь маршрут» и спидометр — пунктами меню «…», а не кнопками.
    /// В поездке справа остаются три: звук, ориентация, «…». Семь кругов
    /// столбиком закрывали треть карты ровно там, где за рулём смотрят на
    /// дорогу (docs/plan_drive_ux_2026-10-07.md, п. 4).
    var keepsMapToolsInMenu: Bool { self != .idle }

    /// Где скорость. В навигации верх отдан манёвру, и скорость со знаком
    /// лимита уходит вниз влево, как у навигаторов; без маршрута HUD остаётся
    /// сверху — на экране нет ничего главнее его.
    var speedPlacement: SpeedPlacement {
        self == .navigating ? .bottomLeading : .top
    }

    enum SpeedPlacement: Equatable {
        case top
        case bottomLeading
    }

    /// Главный элемент экрана: на нём держится иерархия внимания, всё
    /// остальное обязано быть тише. Двух «главных» одновременно не бывает.
    var focus: Focus {
        switch self {
        case .idle:       return .destination
        case .driving:    return .speed
        case .navigating: return .maneuver
        }
    }

    enum Focus: Equatable {
        case destination   // куда поедем
        case speed         // скорость и ближайшая камера
        case maneuver      // поворот
    }
}

/// Насколько громко экран на стоянке предлагает начать поездку.
///
/// Большая зелёная кнопка «Начать поездку» была главным предметом экрана в
/// покое — то есть приложение спрашивало о том, что знает само: MotionService
/// распознаёт начало движения, и по умолчанию это включено. Спрашивать об
/// известном не только занимает главную точку внимания, но и врёт: человек
/// решает, что без нажатия ничего не запишется, и жмёт кнопку там, где она не
/// нужна.
///
/// Кнопку не отнимаем. Автостарт ошибается (пассажир, такси, парковка), и
/// кто-то хочет записать поездку раньше движения — но она перестаёт быть
/// главной. Прятать её в меню тоже нельзя: это меняет «спрашивает» на
/// «непонятно, где» (plan_app_ui.md, У3).
///
/// На вход — голый признак «поездка начнётся сама», а не сам режим: правило
/// от этого остаётся чистым и проверяется без настроек.
nonisolated enum TripStartPrompt: Equatable {
    /// Большая зелёная кнопка: сама поездка не начнётся, спросить обязаны.
    case primary
    /// Скромная капсула: запасной выход, а не главный предмет экрана.
    case secondary

    static func prominence(startsByItself: Bool) -> TripStartPrompt {
        startsByItself ? .secondary : .primary
    }
}

/// Экран поездки поверх режима: прибытие, итог, чип камеры.
///
/// Режим (MapMode) знает только «стоим / едем / ведём». Карточка «Вы на месте»
/// и «Поездка сохранена» приходят поверх него — и раньше вставали ПОВЕРХ всего:
/// прибытие закрывало кнопки справа, а снизу одновременно висела панель поездки
/// со своим «стоп». Две кнопки «завершить» на одном экране — это вопрос, какая
/// из них настоящая (docs/plan_drive_ux_2026-10-07.md, п. 6).
nonisolated enum TripScreenLayout {

    /// Видна ли карточка прибытия. В поездке — пока её не закрыли. Поездка уже
    /// кончилась (автостоп у цели) — только если нет «Поездка сохранена»: те же
    /// цифры дважды подряд читаются как сбой.
    static func showsArrival(hasArrival: Bool, isTripActive: Bool,
                             showsTripEnd: Bool) -> Bool {
        guard hasArrival else { return false }
        return isTripActive || !showsTripEnd
    }

    /// Панель поездки внизу — пока на её месте не стоит прибытие: у карточки
    /// своя кнопка «Завершить поездку», и она должна быть единственной.
    static func showsTripBar(mode: MapMode, arrivalShown: Bool) -> Bool {
        mode.showsTripBar && !arrivalShown
    }

    /// Колонка кнопок справа. Под прибытием прячется: карточка — последний
    /// экран поездки, и крутить карту в этот момент незачем.
    static func showsControlColumn(arrivalShown: Bool, isAddingCamera: Bool) -> Bool {
        !arrivalShown && !isAddingCamera
    }

    /// Кнопка колонки справа, которую можно убрать, когда места мало.
    enum ColumnExtra: Hashable, Sendable {
        case layers, compass, overview, threeD, zoom
    }

    /// Какие необязательные кнопки колонки помещаются в просвет.
    ///
    /// Колонка и нижние панели — разные слои экрана, и колонка не знала, где
    /// панели начинаются: в покое с маршрутом «весь маршрут», зум и звук
    /// уходили ПОД карточку маршрута (на SE — на ~250 pt) и не нажимались; в
    /// поездке на SE то же делали плашки «Радар ещё стоял?» и «Что это было?».
    /// Теперь колонка мерит просвет и раздаёт его по важности: обязательные
    /// кнопки (`fixed` — звук, «к себе», «…») не прячутся никогда, остальные
    /// встают, пока есть место, самые нужные первыми. Убранное не потеряно:
    /// зум — щипком, 3D и «весь маршрут» — в меню «…» поездки.
    ///
    /// - `available` — просвет по высоте; 0 и меньше — ещё не измерен,
    ///   тогда показываем всё (первый кадр не должен мигать пустой колонкой).
    /// - `candidates` — (кнопка, сколько мест занимает), по убыванию важности.
    static func columnExtras(available: CGFloat, fixed: Int,
                             candidates: [(ColumnExtra, Int)]) -> Set<ColumnExtra> {
        guard available > 0 else { return Set(candidates.map(\.0)) }
        var free = Int((available + AppConfig.mapColumnSpacing) / AppConfig.mapColumnSlotHeight) - fixed
        var shown = Set<ColumnExtra>()
        for (extra, slots) in candidates where slots <= free {
            shown.insert(extra)
            free -= slots
        }
        return shown
    }

    /// Чип камеры под манёвром: только на подходе или пока камера говорит.
    /// Потеря сигнала — тоже повод: в навигации HUD сверху нет, и «нет GPS»
    /// иначе было бы негде сказать.
    static func showsCameraChip(distance: Double?, isAlerting: Bool,
                                isSignalStale: Bool) -> Bool {
        if isSignalStale || isAlerting { return true }
        guard let distance else { return false }
        return distance <= AppConfig.tripCameraChipMeters
    }

    /// Свежа ли сохранённая поездка для карточки «Поездка сохранена».
    /// Отсчёт — от момента сохранения, а не от последнего фикса записи.
    static func isTripEndFresh(savedAt: Date?, now: Date) -> Bool {
        guard let savedAt else { return false }
        let age = now.timeIntervalSince(savedAt)
        return age >= 0 && age < AppConfig.tripEndCardFreshSeconds
    }
}
