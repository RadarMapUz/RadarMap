//  Тона схемы приборки.
//
//  До этого файла всё полотно схемы было `.white.opacity(…)` от 0.11 до 0.34.
//  Это давало ЧЕРТЁЖ на чёрном: линии разной яркости, но одного вещества.
//  Настоящий навигатор отличается от чертежа не геометрией, а тем, что дорога
//  у него — асфальт с краями, лежащий НА земле, а не штрих поверх пустоты.
//
//  Схема остаётся тёмной, и это не стилистика: приборку смотрят ночью с
//  держателя, и светлое полотно во весь экран слепит. Поэтому взят ночной
//  язык больших навигаторов — земля темнее асфальта, кайма темнее земли.
//  Кайма здесь несёт работу, а не украшение: без неё две параллельные улицы
//  в 15 метрах сливаются в одну широкую.
//

import SwiftUI

nonisolated enum SketchPalette {

    // MARK: - Время суток

    /// Дневная схема — не «то же светлее», а другое ОТНОШЕНИЕ тонов.
    ///
    /// Ночью полотно светлее земли, днём — темнее её. Глаз читает дорогу по
    /// контрасту с окружением, а не по абсолютному тону, и простое осветление
    /// всех цветов даёт белёсую кашу, в которой асфальт неотличим от газона.
    ///
    /// Что НЕ меняется: камера, сигналы светофора и метка машины. Камера —
    /// единственный объект, ради которого приложение существует, и её
    /// заметность не должна зависеть от времени суток.
    ///
    /// Флаг пишется один раз на смену режима из главного потока и читается
    /// отрисовкой; гонки здесь нет по построению, поэтому и замка нет.
    nonisolated(unsafe) static var daylight = false

    private static func tone(_ night: Color, _ day: Color) -> Color {
        daylight ? day : night
    }


    // MARK: - Земля

    /// Земля под дорогами. НЕ чистый чёрный, и это работа, а не вкус: на
    /// чёрном полотно висит в пустоте, на земле — лежит. Ровно эта разница
    /// отделяет карту от чертежа сильнее, чем любой подбор тонов.
    ///
    /// Про батарею. Чёрный на OLED не жжёт пиксели, и проект за это держится —
    /// но здесь платить почти не за что. В машине картинка стримится с
    /// телефона, а сам телефон в это время показывает чёрный экран передачи:
    /// земля на головном устройстве бесплатна. На приборке телефона схема —
    /// полоса в двести пунктов, а не полный экран. Тон взят у самого края
    /// видимости: он отделяет дорогу от фона и почти не будит матрицу.
    static var ground: Color { tone(Color(red: 0.055, green: 0.062, blue: 0.075), Color(red: 0.902, green: 0.898, blue: 0.878)) }

    /// Квартал — грань дорожного графа. Едва светлее земли: он не сообщает
    /// ничего сам по себе, он ЗАКРЫВАЕТ пустоту между улицами и даёт городу
    /// зернистость. Заметный тон превратил бы карту в шахматную доску.
    static var block: Color { tone(Color(red: 0.085, green: 0.092, blue: 0.105), Color(red: 0.858, green: 0.854, blue: 0.836)) }

    /// Зелень — приглушённая: парк это ориентир, а не предмет внимания.
    static var green: Color { tone(Color(red: 0.09, green: 0.16, blue: 0.11), Color(red: 0.780, green: 0.845, blue: 0.746)) }

    /// Вода — ЕДИНСТВЕННЫЙ насыщенный цвет на всей схеме, и это не украшение.
    /// На тёмном сером фоне синее пятно опознаётся быстрее любой формы:
    /// водитель узнаёт район по реке раньше, чем прочитает хоть одну улицу.
    static var water: Color { tone(Color(red: 0.09, green: 0.20, blue: 0.36), Color(red: 0.640, green: 0.780, blue: 0.900)) }
    static var waterEdge: Color { tone(Color(red: 0.16, green: 0.32, blue: 0.52), Color(red: 0.480, green: 0.640, blue: 0.790)) }

    /// Тротуар. Холоднее и глуше асфальта, и это работа: тротуар обязан
    /// читаться как НЕ дорога с первого взгляда — иначе водитель на схеме
    /// увидит проезд там, где бордюр. Одного тона тут мало, поэтому он ещё и
    /// тоньше всего остального.
    /// Кромка полотна — бордюр.
    ///
    /// Делает для «настоящести» больше, чем любой подбор оттенков: без неё
    /// асфальт висит в пустоте на тёмном фоне и сливается с землёй на светлом.
    /// Чуть светлее асфальта ночью и чуть темнее его днём — как и всё
    /// остальное, кромка живёт КОНТРАСТОМ к соседу, а не своим тоном.
    static var kerb: Color {
        tone(Color(red: 0.36, green: 0.36, blue: 0.35),
             Color(red: 0.470, green: 0.465, blue: 0.450))
    }

    /// Разделительная полоса. Земля, а не асфальт: чуть темнее полотна ночью,
    /// чуть светлее днём — то же правило контраста, что у всего остального.
    static var median: Color {
        tone(Color(red: 0.105, green: 0.115, blue: 0.120),
             Color(red: 0.845, green: 0.850, blue: 0.820))
    }

    static var sidewalk: Color { tone(Color(red: 0.24, green: 0.26, blue: 0.30), Color(red: 0.760, green: 0.756, blue: 0.742)) }

    /// Дом. Светлее квартала ровно настолько, чтобы застройка читалась ВНУТРИ
    /// квартала, и не светлее: дом на схеме — фон последних двухсот метров, а
    /// не предмет внимания. Светлый дом превратил бы город в белую сыпь, по
    /// которой не найти ни дорогу, ни поворот.
    static var house: Color { tone(Color(red: 0.13, green: 0.138, blue: 0.152), Color(red: 0.812, green: 0.806, blue: 0.790)) }

    /// Подпись улицы. Приглушённая почти до земли: имя улицы отвечает на
    /// вопрос «где я», а не «куда сворачивать», и спорить за внимание с
    /// камерой и поворотом оно не должно. Читается за счёт тени по земле, а
    /// не за счёт яркости.
    static var label: Color { tone(Color(red: 0.62, green: 0.65, blue: 0.70), Color(red: 0.240, green: 0.250, blue: 0.270)) }

    /// Корпус светофора снизу: темнее верха, отчего предмет читается объёмным
    /// при одной заливке вместо трёх слоёв.
    static let signalCase = Color(red: 0.055, green: 0.062, blue: 0.075)
    /// Блик по верхней кромке корпуса. Светлая линия на тёмном видна и на
    /// солнце — надёжнее любой обводки.
    static let signalGloss = Color.white.opacity(0.22)
    /// Гнездо линзы: без тёмного кольца лампа висит на корпусе, а не сидит.
    static let signalSocket = Color(red: 0.02, green: 0.023, blue: 0.03)
    /// Козырёк над линзой — по нему светофор узнают боковым зрением.
    static let signalVisor = Color(red: 0.16, green: 0.175, blue: 0.2)

    /// Тень дома. Темнее земли, а не светлее: высота читается как объём, а не
    /// как свечение, и ночью ничего не светит.
    static var houseShadow: Color { tone(Color(red: 0.035, green: 0.04, blue: 0.05), Color(red: 0.740, green: 0.735, blue: 0.720)) }

    /// Створ камеры: куда она смотрит. Полупрозрачный и холодный — он даёт
    /// направление, но не спорит за внимание с самой камерой и с дорогой.
    static let cameraGaze = Color(red: 0.35, green: 0.62, blue: 0.78).opacity(0.16)
    /// У тревожной — теплее и заметнее: это уже не контекст, а предупреждение.
    static let cameraGazeAlert = Color(red: 1.0, green: 0.42, blue: 0.42).opacity(0.22)

    /// Рельсы — штрих-пунктир: узнаваемая пиктограмма, а не просто линия.
    static var rail: Color { tone(Color(red: 0.42, green: 0.40, blue: 0.36), Color(red: 0.560, green: 0.545, blue: 0.510)) }

    // MARK: - Полотно

    /// Кайма дороги. ТЕМНЕЕ фона: так полотно читается лежащим на земле, а
    /// соседние полосы разделяются даже там, где они вплотную.
    static var casing: Color { tone(Color(red: 0.00, green: 0.01, blue: 0.02), Color(red: 0.640, green: 0.634, blue: 0.618)) }

    /// Асфальт по классу дороги: крупные дороги светлее и чуть теплее, дворы
    /// холоднее и темнее. Глубина вместо паутины одинаковых линий.
    static func asphalt(_ kind: RoadClass) -> Color {
        // Ночью полотно СВЕТЛЕЕ земли, днём — ТЕМНЕЕ её, и порядок классов
        // при этом сохраняется: магистраль остаётся самой заметной, дворовый
        // проезд — самым скромным. Меняется знак контраста, а не иерархия.
        if daylight {
            switch kind {
            case .motorway, .trunk: return Color(red: 0.560, green: 0.550, blue: 0.530)
            case .primary:          return Color(red: 0.605, green: 0.596, blue: 0.576)
            case .secondary:        return Color(red: 0.650, green: 0.644, blue: 0.628)
            case .tertiary:         return Color(red: 0.694, green: 0.688, blue: 0.674)
            case .residential:      return Color(red: 0.738, green: 0.732, blue: 0.718)
            case .service:          return Color(red: 0.782, green: 0.776, blue: 0.762)
            case .pedestrian, .unknown: return Color(red: 0.820, green: 0.814, blue: 0.800)
            }
        }
        switch kind {
        case .motorway, .trunk: return Color(red: 0.42, green: 0.41, blue: 0.38)
        case .primary:          return Color(red: 0.37, green: 0.36, blue: 0.34)
        case .secondary:        return Color(red: 0.32, green: 0.32, blue: 0.32)
        case .tertiary:         return Color(red: 0.27, green: 0.27, blue: 0.28)
        case .residential:      return Color(red: 0.22, green: 0.22, blue: 0.24)
        case .service:          return Color(red: 0.18, green: 0.18, blue: 0.20)
        case .pedestrian, .unknown: return Color(red: 0.16, green: 0.17, blue: 0.19)
        }
    }

    /// Источник, который класса НЕ ЗНАЕТ (индекс лимитов), получает один
    /// средний тон на всё. Рисовать «магистраль» по догадке нельзя — здесь
    /// это так же недопустимо, как в оповещениях.
    static var asphaltUnknown: Color { tone(Color(red: 0.28, green: 0.28, blue: 0.29), Color(red: 0.600, green: 0.600, blue: 0.605)) }

    /// Тоннель — «под землёй»: заметно глуше всего остального.
    static var asphaltTunnel: Color { tone(Color(red: 0.13, green: 0.13, blue: 0.15), Color(red: 0.700, green: 0.700, blue: 0.712)) }

    /// Осевая разметка. Только на крупных дорогах: на дворовом проезде её нет
    /// и в жизни, а нарисованная — это выдуманная деталь.
    static var centerline: Color {
        // Днём белая осевая на светлом асфальте исчезает. Разметка обязана
        // остаться разметкой: меняем не яркость, а сторону контраста.
        tone(Color(red: 0.88, green: 0.85, blue: 0.72).opacity(0.30),
             Color(red: 0.99, green: 0.98, blue: 0.94).opacity(0.85))
    }

    /// Разделительная между полосами. Бледнее осевой вдвое, и это не оттенок,
    /// а иерархия: осевая делит ВСТРЕЧНЫЕ потоки — её пересекать нельзя;
    /// разделительная делит попутные — её пересекают каждым перестроением.
    /// Одинаковый тон превратил бы два разных запрета в один узор.
    static var laneDivider: Color {
        tone(Color(red: 0.88, green: 0.85, blue: 0.72).opacity(0.16),
             Color(red: 0.99, green: 0.98, blue: 0.94).opacity(0.70))
    }

    /// Краска на асфальте: зебра и стоп-линия. ЯРЧЕ и осевой, и
    /// разделительных, и это иерархия, а не вкус: линии вдоль дороги
    /// сопровождают движение, а поперечная черта его ОСТАНАВЛИВАЕТ. Такое
    /// читают первым.
    static var marking: Color {
        tone(Color(red: 0.94, green: 0.93, blue: 0.88).opacity(0.62),
             Color(red: 1.0, green: 1.0, blue: 0.99).opacity(0.95))
    }

    /// Шевроны односторонней.
    static let chevron = Color.white.opacity(0.32)

    /// Полотно дороги тревожной камеры и её осевая.
    static let cameraRoad = Color(red: 0.46, green: 0.45, blue: 0.42)
    static let cameraRoadAssumed = Color(red: 0.30, green: 0.30, blue: 0.30)

    /// Трек «откуда я приехал» — самый тихий слой: он объясняет прошлое и не
    /// должен спорить с тем, что впереди.
    static let track = Color.white.opacity(0.16)

    // MARK: - Маршрут

    /// Лента маршрута в три слоя: тёмная кайма отделяет её от полотна,
    /// цветное тело — это «куда я еду», светлая жила внутри даёт объём.
    /// Ровно те же три слоя, что у карты машины (см. CarPlayMapView).
    static let routeCasing = Color(red: 0.02, green: 0.10, blue: 0.06)
    static let routeBody = Theme.success
    static let routeCore = Color.white.opacity(0.26)

    /// Пройденное гасим: оно уже не решение, а память.
    static let routePassed = Color.white.opacity(0.22)

    // MARK: - Манёвр

    /// Стрелка манёвра. Белая кайма — как на дорожном знаке: она отделяет
    /// стрелку от любого фона, включая саму ленту маршрута под ней.
    static let maneuverCasing = Color.white.opacity(0.92)
    static let maneuverBody = Theme.accent

    // MARK: - Ручные объекты

    /// Светофор, разворот, лежачий. Тон один на все виды и намеренно
    /// приглушённый: это ориентиры, а не предупреждения. Красным на схеме
    /// говорят только камеры, и делить с ними цвет нельзя — иначе светофор
    /// впереди будет читаться как радар.
    static let mark = Color(red: 0.62, green: 0.66, blue: 0.72)
    static let markPlate = Color(red: 0.10, green: 0.11, blue: 0.13)
    /// Корпус светофора и стойка под ним. Почти чёрный, но не чёрный: на
    /// асфальте чистый чёрный читается как дыра, а не как предмет.
    static let markBody = Color(red: 0.11, green: 0.12, blue: 0.145)
    static let markEdge = Color(red: 0.55, green: 0.59, blue: 0.66)

    /// Линзы светофора. Приглушены намеренно: это пиктограмма, а не работающий
    /// светофор, и три ярких огня на схеме перетянули бы взгляд с дороги.
    /// Красная линза при этом ТЕМНЕЕ и холоднее камерного красного — рядом они
    /// стоят часто, и путать их нельзя.
    static let signalRed = Color(red: 0.78, green: 0.24, blue: 0.24)
    static let signalAmber = Color(red: 0.85, green: 0.62, blue: 0.20)
    static let signalGreen = Color(red: 0.30, green: 0.70, blue: 0.40)

    /// Камера на схеме — кольцо, а не пятно. Заливка тёмная: марка обязана
    /// читаться поверх любого асфальта, а сплошной красный кружок на тёмной
    /// схеме выглядит болячкой, а не значком.
    static let cameraDotFill = Color(red: 0.13, green: 0.09, blue: 0.10)
    static let cameraDotRing = Theme.danger

    // MARK: - «Я»

    /// Курсор машины: объём даётся тремя тонами одного цвета, а не тенью.
    static let meTop = Color(red: 0.42, green: 0.78, blue: 1.0)
    static let meBody = Color(red: 0.16, green: 0.52, blue: 0.96)
    static let meBase = Color(red: 0.08, green: 0.30, blue: 0.68)
}
