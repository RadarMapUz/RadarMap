    static let carPlayWidePointsThreshold: CGFloat = 700
    /// Ширина ленты. Фиксированная, а не доля: содержимое у неё постоянное
    /// (значок, дистанция, тип), и от ширины экрана оно не растёт.
    static let carPlayAheadPanelWidth: CGFloat = 264
    /// Предельное отношение сторон схемы. Масштаб схемы считается от высоты,
    /// поэтому на широком экране по бокам оказывается втрое больше метров, чем
    /// впереди, и дорога вырождается в нитку. Схему держим в этой пропорции,
    /// остальное отдаём ленте.
    ///
    /// 1.85, а не 1.45: на настоящем экране машины (около 950×475 точек после
    /// safe area) полтора оставляли по 55 точек мёртвого поля с каждой стороны
    /// схемы — ряд вставал уже своего места и висел в пустоте. При 1.85 схема
    /// занимает свою половину целиком, а лишние метры по бокам показывают
    /// параллельные улицы, то есть работают.
    static let carPlaySketchMaxAspect: CGFloat = 1.85
    /// Пересчёт ленты не чаще, чем через столько метров.
    static let carPlayAheadStepMeters: CLLocationDistance = 60
    /// …или при таком повороте курса: свернули — впереди совсем другие камеры.
    static let carPlayAheadCourseStepDegrees: CLLocationDegrees = 12
    /// Сколько камер окрестности просматриваем при сборке ленты.
    static let carPlayAheadScanLimit = 160
    /// Зазор между содержимым (схема, лента) и приборной панелью. Панель
    /// стоит на 90 точках от низа, и без этого зазора лента садилась на неё
    /// вплотную: две отдельные плашки читались как одна слипшаяся.
    static let carPlayContentGap: CGFloat = 26
    /// Во сколько раз толще линии схемы на экране машины. До телефона в
    /// держателе 30 см, до экрана в торпеде — около 70: те же полторы точки
    /// там уже на грани видимости.
    static let carPlaySketchStrokeScale: CGFloat = 1.6

    // MARK: - Схема приборки

    /// Наклон схемы, градусы. Двадцать шесть — потолок, за которым дальняя
    /// часть готовой текстуры растягивается настолько, что дорога у горизонта
    /// мылится. Наклон живёт только при чистой дороге: с тревожной камерой в
