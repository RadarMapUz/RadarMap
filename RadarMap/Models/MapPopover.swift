//
//  MapPopover.swift
//  RadarMap
//
//  Карточки-меню поверх карты: «Карта» (слои, кнопка в колонке) и
//  «Оповещения» (быстрые тумблеры, тап по скорости). Открыта — не больше
//  одной, и закрывается любое из них касанием ВНЕ карточки (20.10).
//
//  До 20.10 у «Оповещений» был только крестик, у «Карты» — ничего, кроме
//  повторного нажатия на ту же кнопку и таймера на шесть секунд. Владелец:
//  «каждый раз это непонятно» — человек тыкал в карту рядом, а карточка
//  стояла. Касание мимо меню закрывает меню — так ведут себя все системные
//  поповеры, и рука этого ждёт.
//
//  Касание вне карточки ТОЛЬКО закрывает её: карту не двигает, точку не
//  ставит, кнопку под пальцем не нажимает. Иначе «закрыть» стало бы
//  «закрыть и что-то сделать», и закрывать меню пришлось бы осторожно.
//
//  Чистая логика — MapPopoverTests.
//

import Foundation

nonisolated enum MapPopover: Hashable, CaseIterable {
    /// «Карта»: слои и кнопки масштаба — от кнопки слоёв в колонке.
    case layers
    /// «Оповещения»: звук, вибро, голос — от тапа по скорости.
    case quickToggles

    /// Что случилось вокруг карточки.
    enum Event: Equatable {
        /// Кнопка карточки: кнопка слоёв или тап по скорости.
        case toggle(MapPopover)
        /// Своё закрытие карточки: крестик, «Закрыть» VoiceOver, таймер
        /// простоя, исчезнувшая с экрана кнопка, к которой она привязана.
        /// Закрывает только ЭТУ карточку: запоздавший таймер слоёв не имеет
        /// права закрыть открытые после них «Оповещения».
        case dismissed(MapPopover)
        /// Касание или начало перетаскивания вне карточки.
        case outsideTouch
        /// Открылся лист (поиск, Итоги, диплинк виджета): меню под листом —
        /// карточка, которая встретит человека после него, хотя он о ней забыл.
        case sheetOpened
        /// Поездка началась или кончилась: колонка меняет кнопки (в поездке
        /// слои уходят в меню «…»), а меню, открытое до старта, на ходу никто
        /// не закрывает.
        case tripStateChanged
        /// Приложение ушло в фон.
        case background
    }

    /// Какая карточка открыта после события.
    static func next(_ current: MapPopover?, on event: Event) -> MapPopover? {
        switch event {
        case .toggle(let card):
            // Вторая карточка вместо первой, а не поверх: две открытых — это
            // два вопроса, какая из них сейчас слушает касание.
            return current == card ? nil : card
        case .dismissed(let card):
            return current == card ? nil : current
        case .outsideTouch, .sheetOpened, .tripStateChanged, .background:
            return nil
        }
    }
}
