import Foundation
import CoreLocation
import MapKit

/// `nonisolated` — константы читают чистые движки (`AlertEngine`, `PassTracking`,
/// `CameraDirection`) и `@concurrent`-код; без этого дефолтная изоляция проекта
/// (`SWIFT_DEFAULT_ACTOR_ISOLATION = MainActor`) делает их main-actor-only.
nonisolated enum AppConfig {

    // MARK: - Оповещения / геолокация

    /// Радиус срабатывания оповещения о камере (метры). Вынесено в константу — легко менять.
    static let alertRadius: CLLocationDistance = 400

    /// Максимум одновременно отслеживаемых регионов. Жёсткое ограничение iOS.
    static let maxMonitoredRegions = 20

    /// Насколько пользователь должен сместиться, прежде чем пересчитать окно камер.
    /// Меньше значение — свежее набор камер, чуть больше пробуждений. 1.5 км — баланс для города/трассы.
    static let retileDistance: CLLocationDistance = 1500

    /// Камер в окне кандидатов на оповещение. Геозон iOS даёт только 20, но
    /// движок алертов ими не ограничен: в плотном городе 20-я камера бывает
    /// ближе, чем ретайл плюс радиус оповещения, и камера впереди просто не
    /// попадала в кандидаты — приложение молчало о ней. 150 камер по всей базе
    /// дают окно радиусом не меньше 3.5 км даже в самом плотном месте.
    static let trackedCamerasLimit = 150

    /// Запас покрытия окна: до следующего пересчёта в нём обязаны лежать все
    /// камеры в максимальном радиусе оповещения плюс гистерезис выхода.
    static let trackedCoverageMeters: CLLocationDistance = 1100

    /// Чаще этого окно не пересчитываем, даже если оно узкое (краудсорсные точки
    /// могут сгрудиться в одном районе): пересчёт трогает геозоны, а это IPC.
    static let retileMinDistance: CLLocationDistance = 300

    /// Адаптивный GPS: финальный подход к камере/манёвру — держим максимальную точность
    /// (нужен точный отсчёт расстояния и учёт проезда: зона измерения 80 м попадает сюда).
    static let gpsPreciseApproachMeters: CLLocationDistance = 500
    /// Ближе этого, но дальше «финала» — точность 10 м и реже колбэки: экономим чип и
    /// частоту всего пайплайна. Дальше — ещё мягче. В плотном городе так GPS большую часть
    /// пути идёт на среднем/мягком тире вместо постоянного максимума (меньше нагрев).
    static let gpsMidApproachMeters: CLLocationDistance = 1500
    /// Стоянка в поездке (пробка, светофор, парковка с невыключенной поездкой):
    /// столько секунд без движения — и GPS падает до самого мягкого тира.
    /// 20 с, а не 60: светофор в Ташкенте — 30–120 с, и с минутной выдержкой
    /// половина красного горела на полной точности. Безопасно это стало после
    /// предохранителя близости (gpsStandstillNearCameraMeters): у камеры не
    /// расслабляемся вовсе, а вдали выход мгновенный — первый же фикс с
    /// движением возвращает точный тир.
    nonisolated static let gpsIdleAfterSeconds: TimeInterval = 20
    /// «Стою» — скорость ниже этого (км/ч). Ползание в пробке (1–2 км/ч) —
    /// тоже стоянка: фиксы всё равно приходят по 30-метровому фильтру.
    nonisolated static let gpsStandstillSpeedKmh = 3.0
    /// Ближе этого к камере/манёвру стоянка НЕ расслабляет GPS: зона замера
    /// проезда 80 м плюс запас — очередь ползком у самой камеры пишет проезд
    /// с полной точностью, как и раньше.
    nonisolated static let gpsStandstillNearCameraMeters: CLLocationDistance = 150
    /// Стояночное затемнение приборки: столько секунд без движения — контент
    /// гаснет до ~40% (OLED: тёмные пиксели — настоящие ватты). Выдержка
    /// больше GPS-ной нарочно: гаснуть на каждом коротком светофоре — мигать.
    nonisolated static let dashboardDimIdleSeconds: TimeInterval = 30

    // MARK: - Умный режим оповещений (город/трасса) — пороги детектора.
    // nonisolated: читаются из чистого AlertPolicy (и его тестов) без прыжка на main.

    /// Лимит дороги ≥ этого — голос за трассу (самый сильный сигнал).
    nonisolated static let highwayLimitKmh = 90
    /// Лимит ≤ этого — голос за город.
    nonisolated static let cityLimitKmh = 60
    /// Средняя скорость (EMA ~2 мин) выше — похоже на трассу.
    nonisolated static let highwayAvgSpeedKmh: Double = 78
    /// Средняя ниже — городской ритм со светофорами.
    nonisolated static let cityAvgSpeedKmh: Double = 55
    /// Камер в радиусе 3 км не меньше этого — плотная городская сетка.
    nonisolated static let cityCameraDensity = 6
    /// Контекст не переключается чаще: светофор на трассе — ещё не город.
    nonisolated static let alertContextSwitchSeconds: TimeInterval = 180

    // MARK: - Качество GPS-фикса (LocationFilter)

    /// Погрешность координаты, выше которой фикс в алерты и трек не пускаем.
    /// 65 м — городской каньон ещё проходит, «сотка» из подземного паркинга нет.
    static let maxHorizontalAccuracyMeters = 65.0

    /// Насколько старым может быть фикс. Первый фикс после запуска или туннеля
    /// часто кэшированный со старого места — именно он давал ложные проезды.
    static let maxFixAgeSeconds = 10.0

    /// Точность курса, при которой сырому курсу можно верить. Хуже — считаем курс
    /// по земле: недостоверный курс ЗАГЛУШИТ настоящую камеру (гейт оси), а это
    /// опаснее лишнего предупреждения.
    static let courseMaxAccuracyDegrees = 25.0

    /// Минимальный сдвиг между фиксами, чтобы считать курс по земле.
    static let derivedCourseMinMeters = 12.0
    /// Дальше этого разрыва прошлая точка уже не опора для курса.
    static let derivedCourseMaxSeconds = 5.0

    /// Точность скорости, выше которой значение не берём (держим прошлое).
    static let maxSpeedAccuracyMps = 5.0

    /// Нереальная скорость между фиксами — признак перелёта координаты.
    static let maxPlausibleSpeedMps = 90.0        // ≈ 324 км/ч
    /// Перелёт при одинаковом штампе времени.
    static let maxPlausibleJumpMeters = 100.0
    /// Разрыв, дольше которого большое смещение законно (стоянка, работа в фоне).
    static let jumpCheckMaxSeconds = 30.0

    /// Без фиксов дольше этого считаем сигнал потерянным: HUD говорит «нет GPS»,
    /// алерты приостановлены, состояние эскалации НЕ сбрасывается — иначе при
    /// возврате сигнала приложение заорёт про ту же камеру заново.
    static let gpsStaleSeconds = 8.0

    /// Медленнее этого «нет сигнала» не объявляем: на стоянке и в пробке фиксы
    /// законно не приходят — их не пускает distanceFilter, а не спутники.
    static let staleWatchdogMinSpeedKmh = 5.0

    /// Во сколько раз ждём дольше ожидаемого интервала между фиксами
    /// (distanceFilter / скорость), прежде чем объявить потерю сигнала.
    static let staleWatchdogSlack = 2.5
    /// Потолок ожидания: дольше этого молчание — точно потеря, а не фильтр.
    static let staleWatchdogMaxSeconds = 30.0

    /// Насколько камера может «уехать назад» по маршруту, прежде чем считаем её
    /// пройденной и убираем из кандидатов на предупреждение.
    static let routePassedToleranceMeters = 60.0

    // MARK: - Дорога камеры (направление, полосы, кусок проезжей части)
    // nonisolated: читаются из чистых RoadShape/RoadCorridor и их тестов.

    /// Ширина одной полосы — из неё считается ширина проезжей части.
    nonisolated static let laneWidthMeters = 3.5

    /// Запас к половине ширины дороги: координата камеры в реестре смещена, GPS
    /// шумит. Меньше — начнём терять камеры на своей же дороге.
    nonisolated static let roadPositionSlackMeters = 8.0

    /// Расхождение курса с НАПРАВЛЕНИЕМ односторонней проезжей части, после
    /// которого камера не наша: 90° — это уже поперёк, 100 даёт запас на дугу
    /// развязки, но обратную сторону (180°) отсекает уверенно.
    nonisolated static let cameraDirectionMaxAngle = 100.0

    /// Минимальный допуск проверки по куску дороги (когда GPS отличный).
    nonisolated static let roadShapeMinToleranceMeters = 10.0

    /// Разнос проезжих частей разделённой дороги. Ровно с этим радиусом снап
    /// искал обратную сторону, когда помечал дорогу разделённой
    /// (server/snap_cameras.py, opposite_carriageway) — значит обратная полоса
    /// заведомо внутри него. Камера, которая может снимать обе стороны, обязана
    /// считать своей и её, иначе мы промолчим ровно там, где она стреляет.
    nonisolated static let dividedRoadSpanMeters: CLLocationDistance = 60

    /// Пол ближней зоны коридора: он мерится от линии нашего курса, точность
    /// которой ограничена GPS — узкий коридор начал бы терять свои же камеры.
    nonisolated static let corridorMinNearMeters = 18.0

    // MARK: - Карта

    /// Центр Узбекистана — запасная позиция карты, пока нет геопозиции пользователя.
    static let uzbekistanRegion = MKCoordinateRegion(
        center: CLLocationCoordinate2D(latitude: 41.377, longitude: 64.585),
        span: MKCoordinateSpan(latitudeDelta: 8.0, longitudeDelta: 12.0)
    )

    /// Бюджет аннотаций на экране. Камер в области больше — область
    /// кластеризуется целиком (CameraMapContent), и ни одна камера не пропадает:
    /// раньше лишние молча отбрасывались и карта выглядела «недогруженной».
    static let maxVisibleAnnotations = 220

    /// Средний зум (шире этого по широте): камеры рисуются маленькими точками,
    /// полноразмерный пин — только у ближайшей и выбранной. Карта не превращается в кашу.
    static let dotModeSpanDegrees = 0.035

    /// Во сколько раз расширяем видимую область при подгрузке аннотаций.
    /// Буфер держит точки уже отрисованными за краями экрана → панорамирование без «подпрыгивания».
    static let annotationBufferFactor = 1.8

    /// Насколько сильно должна измениться область, чтобы пересчитать аннотации (доля буфера).
    /// Небольшие сдвиги внутри буфера пропускаем — это и есть «умный» зум.
    static let recomputeThreshold = 0.35

    // MARK: - Карта проездов (Итоги)

    /// Сторона ячейки сетки, в которой считаем частоту проездов по участку.
    /// 20 м ≈ ширина дороги: два прохода по одной улице попадают в одну ячейку,
    /// параллельные улицы — в разные.
    static let heatCellMeters = 20.0

    /// Проездов, с которых участок считается повторяющимся (средний градус линии).
    static let heatRepeatedTimes = 2

    /// Проездов, с которых участок — постоянный коридор (яркая толстая линия).
    static let heatFrequentTimes = 5

    /// Потолок числа ломаных слоя частоты. Шум GPS может чередовать попадание в
    /// ячейку и дробить трек на куски — за потолком рисуем по одной линии на
    /// поездку: карта важнее градусов.
    static let heatMaxLines = 400

    /// Дистанция камеры (метры) при центрировании на выбранной камере из списка.
    static let focusDistance: CLLocationDistance = 1200

    /// На широких зумах камеры группируются в кластеры: сетка N×N ячеек на экран.
    static let clusterGridDivisions = 5.0

    // MARK: - Направленные оповещения (только камеры впереди по курсу)

    /// Минимальная скорость, при которой GPS-курс достоверен и включается фильтр направления.
    static let directionalMinSpeedKmh: Double = 10
    /// Половина сектора «прямо»: камера в ±этого от курса — впереди, не «сбоку».
    /// Широкая (координаты камер в базе смещены вбок от полосы на десятки метров).
    static let directionAheadDeadZone: Double = 40

    // MARK: - Коридор дороги (фильтр «камера на нашей дороге»)
    // nonisolated: читаются из чистого RoadCorridor (и его тестов) без прыжка на main.
    //
    // Угловой фильтр сам по себе не различает дороги: ±70° на дистанции 400 м
    // пропускает камеру в 400·sin70° ≈ 375 м вбок, то есть параллельные улицы,
    // дублёры и эстакады. Поэтому решает боковое отклонение от линии курса, и вблизи
    // коридор узкий (курс достоверен, кривизна не успевает набежать), а вдали
    // расширяется малым конусом — дорога впереди может повернуть.

    /// Ближняя зона: до этого удаления коридор не расширяется.
    nonisolated static let corridorNearFieldMeters: CLLocationDistance = 150
    /// Полуширина коридора в городе: полоса + погрешность координат в базе.
    /// Узкая намеренно — параллельных улиц в городе больше всего.
    nonisolated static let corridorCityMeters: CLLocationDistance = 30
    /// На трассе шире: разделительная полоса, широкие развязки, разрежённая база.
    nonisolated static let corridorHighwayMeters: CLLocationDistance = 55
    /// За ближней зоной коридор растёт с этим наклоном (0.15 ≈ 8.5°):
    /// на 400 м допуск ~68 м — вчетверо строже прежних ±70°.
    nonisolated static let corridorFarSlope: Double = 0.15
    /// Потолок расширения. Наклон рос без ограничения, и это было терпимо,
    /// пока радиус оповещения не превышал 670 м. С трассовым запасом в 29
    /// секунд камера рассматривается за 1047 м, а там прежняя формула давала
    /// допуск 190 м вбок — это уже не «дорога повернула», это соседнее шоссе
    /// и дублёр за посадкой.
    ///
    /// Потолок ничего не ломает на кривых: коридор пересчитывается на каждом
    /// фиксе, а `Decision.isFirst` даёт полноценный голос и поздно замеченной
    /// камере. Худшее следствие — на сильно изогнутой трассе о камере скажут
    /// не за 29 секунд, а за 20, когда дорога довернёт. Лучшее — молчание про
    /// камеру на встречном шоссе за разделительной.
    nonisolated static let corridorCityMaxMeters: CLLocationDistance = 90
    nonisolated static let corridorHighwayMaxMeters: CLLocationDistance = 140
    /// Немного «позади» тоже считаем своей камерой: на самом траверзе продольная
    /// составляющая шумит вокруг нуля, и предупреждение не должно гаснуть.
    nonisolated static let corridorBehindToleranceMeters: CLLocationDistance = 30
    /// Курс отклоняется от оси дороги камеры больше этого — мы НЕ на её дороге
    /// (мост над камерой, перпендикулярная улица развязки). Порог щедрый:
    /// шум GPS-курса + кривые подъезды не должны глушить свою камеру.
    nonisolated static let cameraAxisMaxAngle: Double = 55

    /// Умный радиус: предупреждаем за N секунд до камеры, а не за фиксированные метры.
    ///
    /// Запас времени зависит от скорости не только через метры, но и сам по
    /// себе. В городе 22 секунды — это ровно столько, сколько нужно, чтобы
    /// снять ногу с газа; предупреждать раньше вредно, камеры стоят часто и
    /// фразы начинают наезжать друг на друга.
    ///
    /// На трассе всё иначе. Там 22 секунды на 110 км/ч — это 670 метров, и
    /// водитель получает предупреждение уже видя знак камеры глазами. Сбросить
    /// со 130 до 90 — это метров триста пути и секунд десять, а ещё нужно
    /// оглядеться, кто едет сзади, и перестроиться. Отсюда 29 секунд: на
    /// 110 км/ч — 886 метров, на 130 — 1047. Ровно та просьба, с которой
    /// начался этот разбор: «на трассе не 400 метров, а чуть больше».
    static let alertLeadTimeSeconds: Double = 22
    static let alertLeadTimeHighwaySeconds: Double = 29
    /// Между этими скоростями запас плавно переходит от городского к
    /// трассовому. Скачок в одной точке дал бы камеру, которая «то видна, то
    /// нет», когда стрелка дрожит вокруг порога.
    static let alertLeadRampFromKmh: Double = 80
    static let alertLeadRampToKmh: Double = 100
    /// Потолок динамического радиуса (метры). Поднят с 1000 вместе с трассовым
    /// запасом: на 130 км/ч прежний потолок срезал бы его до 27.7 секунды.
    static let maxDynamicRadius: CLLocationDistance = 1100

    /// Медленнее этого голос молчит: в пробке и на светофоре камера в 300 м
    /// впереди — не решение водителя, а панель и тук её всё равно показывают.
    nonisolated static let voiceMinSpeedKmh: Double = 20

    /// Камеры, стоящие ближе этого друг к другу, озвучиваются ОДНОЙ фразой: на
    /// большом перекрёстке их две-три, и раздельные анонсы наезжают один на
    /// другой. Про сгруппированные камеры голос уже сказал — их собственная
    /// фраза пропускается, но тук и баннер остаются.
    static let voiceGroupMeters: CLLocationDistance = 150

    /// Зона измерения скорости на подходе к камере — так меряет настоящий радар.
    /// Минимум из этой зоны и есть «скорость проезда»: разгон после камеры и
    /// смещённая координата в реестре оценку не завышают.
    static let passZoneMeters: CLLocationDistance = 80

    /// Траверз, ближе которого камера считается ПРОЙДЕННОЙ.
    ///
    /// Это не то же, что зона измерения, хотя раньше было одной константой.
    /// Восемьдесят метров — правильная ширина для «начать мерить скорость» и
    /// заведомо слишком много для «я проехал под этой камерой»: на развязке
    /// камера соседней улицы всегда оказывается в 80 м, и её проезд писался в
    /// историю. Камера снимает проезжую часть, над которой стоит: половина
    /// ширины проспекта (13–20 м) плюс шум GPS — это сорок метров с запасом.
    static let passTraverseMaxMeters: CLLocationDistance = 40

    /// Тот же траверз для камер БЕЗ дорожного профиля — свои точки и
    /// краудсорсные отметки. Их координату ставил человек, а не снап по оси
    /// дороги, поэтому сужать порог там нельзя: потеряем настоящие проезды.
    static let passTraverseNoProfileMeters: CLLocationDistance = 80

    /// Боковое отклонение от проезжей части камеры, после которого проезд
    /// отклоняется: мы ехали по другой дороге. Порог заведомо щедрый — половина
    /// ширины дороги умножается на запас, и всё равно не меньше 35 м. Отклоняем
    /// только по ДОКАЗАТЕЛЬСТВУ: цена ошибки в две стороны разная — лишняя
    /// запись стоит баллов рейтинга и чужого перекрёстка в разборе, потерянная
    /// — лишь занижённой статистики.
    static let passOffRoadMeters: CLLocationDistance = 35
    static let passOffRoadFactor = 2.5

    /// Гистерезис выхода из зоны оповещения: серия порогов сбрасывается только
    /// когда камера ушла заметно дальше радиуса — анти-дребезг на границе.
    static let alertExitHysteresisMeters: CLLocationDistance = 80

