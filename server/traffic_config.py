                             # предлагает 1 кусок с подписью «по данным
                             # водителей»; не снижено — см. TRAFFIC.md,
                             # «Порог карты»: одиночный кусок в now.json,
                             # обновляемом раз в 2 минуты, — это след одной
                             # машины почти в реальном времени (инвариант 7)

