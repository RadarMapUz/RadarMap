    static let breakdownVisibleRows = 5
    /// Ниже этого вклада строка уходит в «остальные поездки».
    static let breakdownMinPoints = 0.5
    /// Столько камер показываем в расшифровке штрафов.
    static let fineSourcesVisibleRows = 5
    /// Столько мест «где теряете баллы» показываем сразу.
    static let hotspotsVisibleRows = 4
    /// По скольким прошлым окнам считаем «вашу норму» рейтинга.
    static let ratingBaselinePeriods = 8
    /// Меньше этого числа окон с поездками — нормы ещё нет, сравнивать не с чем.
    static let ratingBaselineMinPeriods = 3

    // MARK: - Карта: важность и направление маркера

    /// До какого расстояния камера считается «моей» и рисуется в полную силу.
    /// Дальше — фон: он нужен как контекст, но не должен спорить за взгляд.
    /// Полтора километра — примерно то, что помещается на экране в городском
