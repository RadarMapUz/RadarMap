//
//  LimitConfidence.swift
//  RadarMap
//
//  Можно ли считать найденный лимит фактом.
//
//  Жалоба с дороги: «в Ташкенте нет лимита 50 км/ч». Замер по боевой базе
//  подтвердил и усилил её: в границах города 99,7 % сегментов несут лимит ниже
//  70, причём 84,6 % — ровно 60. По ПДД РУз в населённом пункте 70.
//
//  Цена этой разницы не косметическая. Лимит на 10 ниже реального превращает
//  законную езду в «превышение», а из превышения растёт всё остальное: сирена
//  вместо спокойной фразы у камеры, минус в рейтинге, сумма возможного штрафа
//  и — через CameraFamiliarity — камера, которая уже никогда не замолчит.
//
//  Отличить «здесь правда 40 у школы» от «в OSM проставили 60 всему городу»
//  приложение не может и не должно притворяться, что может. Поэтому решение
//  здесь не про ЦИФРУ, а про ПОСЛЕДСТВИЯ: сомнительный лимит показываем (со
//  знаком «≈»), но не превращаем в обвинение.
//
//  Чистое правило без SwiftUI и без сети — покрыто LimitConfidenceTests.
//

import Foundation

nonisolated enum LimitConfidence: Equatable {
    /// Верим: считаем превышение, называем сумму, отнимаем рейтинг.
    case signed
    /// Сомневаемся: показываем со знаком «≈», но нарушением не считаем.
    case doubtful

    /// `roadClass` — класс дороги, по которой едем: из базы лимитов (формат 2)
    /// либо, пока её нет, класс дороги ближайшей камеры. `.unknown` означает
    /// «не знаем» — и тогда мы НЕ сомневаемся: догадка не вправе отменять
    /// данные, у неё для этого нет оснований.
    static func of(limitKmh: Int, roadClass: RoadClass,
                   inSettlement: Bool) -> LimitConfidence {
        // Только в населённом пункте. За городом тег обычно и есть правда: 90
        // на трассе встречается по-настоящему, и объявлять его сомнительным
        // значило бы отменить превышение там, где оно настоящее. Жалоба, из
        // которой всё выросло, тоже городская.
        guard inSettlement else { return .signed }
        // Малый класс — малый лимит законен: двор, служебный проезд, улица.
        guard roadClass.isMajor else { return .signed }
        // Сколько по ПДД положено на такой дороге, если знака нет.
        guard let byLaw = roadClass.assumedLimitKmh(inSettlement: inSettlement) else {
            return .signed
        }
        // Тег НИЖЕ законного умолчания на магистральной дороге. Так бывает
        // (ремонт, школа, мост), но в Ташкенте так размечен весь город —
        // значит это свойство данных, а не дороги.
        return limitKmh < byLaw ? .doubtful : .signed
    }
}
