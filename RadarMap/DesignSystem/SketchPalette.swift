//
//  Тона схемы приборки.
//
//  До этого файла всё полотно схемы было `.white.opacity(…)` от 0.11 до 0.34.
//  Это давало ЧЕРТЁЖ на чёрном: линии разной яркости, но одного вещества.
//  Настоящий навигатор отличается от чертежа не геометрией, а тем, что дорога
//  у него — асфальт с краями, лежащий НА земле, а не штрих поверх пустоты.
//
//  Ночью схема тёмная, и это не стилистика: приборку смотрят ночью с
//  держателя, и светлое полотно во весь экран слепит. Земля темнее асфальта,
//  кайма темнее земли. Кайма несёт работу, а не украшение: без неё две
//  параллельные улицы в пятнадцати метрах сливаются в одну широкую.
//
//  ЦВЕТ ЗДЕСЬ — ЧИСЛО. У каждого тона есть контраст к соседям, он посчитан по
//  формуле относительной яркости и закреплён тестом (SketchPaletteTests).
//  Так вышло не из любви к таблицам: дневная схема год простояла на контрасте
//  1,04–1,25 между землёй, кварталами и домами — то есть города на ней не
//  было видно вовсе, и на четырёх снимках живой поездки 60–82 % кадра
//  занимал один ровный тон.
//

import SwiftUI

nonisolated enum SketchPalette {

    // MARK: - Тон

    /// Тон схемы: три составляющих, а не готовый `Color`.
    ///
    /// Готовый Color не отвечает на вопрос «какой у вас контраст» — SwiftUI не
    /// отдаёт составляющие обратно. А контраст здесь не украшение, а условие
    /// работы: тест обязан уметь пересчитать таблицу, иначе «поярче» снова
    /// станет решением на глаз.
    struct Tone: Equatable, Sendable {
        let red: Double
        let green: Double
        let blue: Double

        init(_ red: Double, _ green: Double, _ blue: Double) {
            self.red = red
            self.green = green
            self.blue = blue
        }

        var color: Color { Color(red: red, green: green, blue: blue) }
        func color(_ opacity: Double) -> Color { color.opacity(opacity) }

        /// Относительная яркость (WCAG): та же формула, по которой считались
        /// контрасты панели, чтобы числа двух половин проекта сравнивались.
        var luminance: Double {
            func part(_ value: Double) -> Double {
                value <= 0.04045 ? value / 12.92 : pow((value + 0.055) / 1.055, 2.4)
            }
            return 0.2126 * part(red) + 0.7152 * part(green) + 0.0722 * part(blue)
        }

        /// Тот же тон строкой «#rrggbb» — для стиля движка карты: он говорит
        /// на языке CSS, а не на языке SwiftUI.
        var hex: String {
            func part(_ value: Double) -> Int {
                Int((min(max(value, 0), 1) * 255).rounded())
            }
            return String(format: "#%02x%02x%02x", part(red), part(green), part(blue))
        }

        /// Контраст к другому тону. Единица — тона неразличимы.
        func contrast(to other: Tone) -> Double {
            let mine = luminance, theirs = other.luminance
            return (max(mine, theirs) + 0.05) / (min(mine, theirs) + 0.05)
        }
    }

    // MARK: - Время суток

    /// Дневная схема — не «то же светлее», а другое ОТНОШЕНИЕ тонов.
    ///
    /// Ночью полотно светлее земли. Днём — СВЕТЛЕЕ ТОЖЕ, и это разворот
    /// прежнего решения. Раньше днём асфальт был темнее земли, а земля стояла
    /// у самого белого (0,90) — и всему остальному оставалась полоса
    /// контраста от 1,0 до 1,25, то есть невидимая. Так устроены все дневные
    /// карты, и не из вкуса: белая дорога на сером городе оставляет место и
    /// кварталам, и домам, и зелени, и воде.
    ///
    /// Что НЕ меняется: камера, сигналы светофора и метка машины. Камера —
    /// единственный объект, ради которого приложение существует, и её
    /// заметность не должна зависеть от времени суток.
    ///
    /// Флаг пишется один раз на смену режима из главного потока и читается
    /// отрисовкой; гонки здесь нет по построению, поэтому и замка нет.
    nonisolated(unsafe) static var daylight = false

    private static func pick(_ night: Tone, _ day: Tone) -> Tone {
        daylight ? day : night
    }

    // MARK: - Земля

    /// Земля под дорогами. НЕ чистый чёрный, и это работа, а не вкус: на
    /// чёрном полотно висит в пустоте, на земле — лежит. Ровно эта разница
    /// отделяет карту от чертежа сильнее, чем любой подбор тонов.
    ///
    /// Про батарею. Чёрный на OLED не жжёт пиксели, и проект за это держится —
    /// но здесь платить почти не за что. В машине картинка стримится с
    /// телефона, а сам телефон в это время показывает чёрный экран передачи.
    /// Тон взят у самого края видимости: он отделяет дорогу от фона и почти не
    /// будит матрицу.
    ///
    /// Днём земля СЕРАЯ, а не белая: белая земля не оставляет места ничему.
    static var groundTone: Tone { pick(Tone(0.055, 0.062, 0.075),
                                       Tone(0.836, 0.830, 0.812)) }
    static var ground: Color { groundTone.color }

    /// Квартал — грань дорожного графа. Он не сообщает ничего сам по себе, он
    /// ЗАКРЫВАЕТ пустоту между улицами и даёт городу массу.
    ///
    /// Контраст к земле: 1,35 днём и 1,17 ночью — против 1,11 и 1,07, на
    /// которых города на схеме не было видно. Верхняя граница тоже есть:
    /// заметнее дороги квартал быть не вправе, иначе схема превращается в
    /// шахматную доску.
    ///
    /// Ночной тон опущен на 0,007 от первой редакции не ради самого квартала,
    /// а ради дома: тот стоял к нему на 1,10, то есть сливался с ним. Опускать
    /// квартал дешевле, чем осветлять дом: у дома сверху потолок — он обязан
    /// остаться тусклее проезда, — а у квартала снизу оставался запас до земли.
    static var blockTone: Tone { pick(Tone(0.118, 0.127, 0.145),
                                      Tone(0.722, 0.718, 0.701)) }
    static var block: Color { blockTone.color }

    /// Зелень — приглушённая: парк это ориентир, а не предмет внимания. Но
    /// РАЗЛИЧИМАЯ: 1,28 к земле днём вместо 1,19, и тон уводится в зелёный
    /// сильнее, чем раньше, — на дневной карте цвет работает лучше яркости.
    static var greenTone: Tone { pick(Tone(0.107, 0.195, 0.127),
                                      Tone(0.666, 0.766, 0.616)) }
    static var green: Color { greenTone.color }

    /// Вода — ЕДИНСТВЕННЫЙ насыщенный цвет на всей схеме, и это не украшение.
    /// Синее пятно опознаётся быстрее любой формы: водитель узнаёт район по
    /// реке раньше, чем прочитает хоть одну улицу. Поэтому у неё и самый
    /// высокий контраст из всей местности — 1,80 ночью, 1,75 днём.
    static var waterTone: Tone { pick(Tone(0.121, 0.250, 0.404),
                                      Tone(0.477, 0.649, 0.781)) }
    static var water: Color { waterTone.color }
    static var waterEdgeTone: Tone { pick(Tone(0.16, 0.32, 0.52),
                                          Tone(0.410, 0.529, 0.628)) }
    static var waterEdge: Color { waterEdgeTone.color }

    /// Тротуар. Обязан читаться как НЕ дорога с первого взгляда — иначе
    /// водитель на схеме увидит проезд там, где бордюр. Ночью он тусклее
    /// асфальта, днём — темнее его: в обоих случаях на ступень «тише».
    static var sidewalkTone: Tone { pick(Tone(0.156, 0.170, 0.196),
                                         Tone(0.887, 0.883, 0.873)) }
    static var sidewalk: Color { sidewalkTone.color }

    /// Кромка полотна — бордюр.
    ///
    /// Делает для «настоящести» больше, чем любой подбор оттенков: без неё
    /// асфальт висит в пустоте на тёмном фоне и сливается с землёй на светлом.
    /// Кромка живёт КОНТРАСТОМ к соседу, а не своим тоном: 1,95 к полотну.
    static var kerbTone: Tone { pick(Tone(0.36, 0.36, 0.35),
                                     Tone(0.698, 0.691, 0.674)) }
    static var kerb: Color { kerbTone.color }

    /// Разделительная полоса. Земля, а не асфальт: на проспекте потоки
    /// разделены газоном или отбойником, и рисовать там краску значит
    /// утверждать, что это разметка.
    static var medianTone: Tone { pick(Tone(0.113, 0.121, 0.128),
                                       Tone(0.771, 0.780, 0.750)) }
    static var median: Color { medianTone.color }

    /// Дом. Светлее квартала ночью и темнее его днём ровно настолько, чтобы
    /// застройка читалась ВНУТРИ квартала, и не больше: дом на схеме — фон
    /// последних двухсот метров, а не предмет внимания.
    ///
    /// Ночью дом обязан оставаться ТУСКЛЕЕ самой мелкой дороги (проезда),
    /// иначе застройка читается сетью. Днём это ограничение снимается само:
    /// там дороги светлые, а дома тёмные, как на любой дневной карте.
    ///
    /// Ночью к кварталу — 1,15 (было 1,10, и на этом числе застройка была
    /// одним пятном с ним). Выше поднимать нельзя: потолок — яркость проезда,
    /// до неё остаётся 12 %.
    static var houseTone: Tone { pick(Tone(0.162, 0.169, 0.187),
                                      Tone(0.660, 0.654, 0.638)) }
    static var house: Color { houseTone.color }

    /// Контур дома.
    ///
    /// Новое и самое дешёвое из всего, что делает застройку застройкой. На
    /// дневной карте дома различают по КОНТУРУ, а не по заливке: без него
    /// девяносто домов в кадре сливаются в одно серое поле — ровно то, что
    /// было на снимках. Контраст к заливке 1,5 днём и 1,32 ночью.
    static var houseEdgeTone: Tone { pick(Tone(0.232, 0.243, 0.270),
                                          Tone(0.533, 0.527, 0.516)) }
    static var houseEdge: Color { houseEdgeTone.color }

    /// Подпись улицы. Приглушённая относительно вывесок, но ЧИТАЕМАЯ: 8,5 к
    /// земле. Имя улицы отвечает на вопрос «где я», и спорить за внимание с
    /// камерой ему незачем — оно и не спорит: его читают, когда ищут.
    static var labelTone: Tone { pick(Tone(0.62, 0.65, 0.70),
                                      Tone(0.191, 0.200, 0.222)) }
    static var label: Color { labelTone.color }

    /// Имя населённого пункта. Ярче названия улицы, и это не украшение:
    /// на обзорном охвате оно единственное, что отвечает на вопрос «где я»,
    /// а улиц там нет вовсе. Контраст к земле 12,5 против 8,5 у улицы.
    static var placeLabelTone: Tone { pick(Tone(0.80, 0.82, 0.86),
                                           Tone(0.09, 0.10, 0.12)) }
    static var placeLabel: Color { placeLabelTone.color }

    /// Корпус светофора снизу: темнее верха, отчего предмет читается объёмным
    /// при одной заливке вместо трёх слоёв.
    static let signalCase = Color(red: 0.055, green: 0.062, blue: 0.075)
    /// Блик по верхней кромке корпуса. Светлая линия на тёмном видна и на
    /// солнце — надёжнее любой обводки.
    static let signalGloss = Color.white.opacity(0.22)
    /// Гнездо линзы: без тёмного кольца лампа висит на корпусе, а не сидит.
    static let signalSocket = Color(red: 0.02, green: 0.023, blue: 0.03)
    /// Козырёк над линзой — по нему светофор узнают боковым зрением.
    static let signalVisor = Color(red: 0.16, green: 0.175, blue: 0.2)

    /// Тень дома. Темнее земли в обеих темах: высота читается как объём, а не
    /// как свечение, и ночью ничего не светит.
    static var houseShadowTone: Tone { pick(Tone(0.035, 0.04, 0.05),
                                            Tone(0.632, 0.629, 0.619)) }
    static var houseShadow: Color { houseShadowTone.color }

    /// Затемнение по краю растра. Ночью — в чёрный, днём — В ЗЕМЛЮ.
    ///
    /// Чёрная виньетка на светлой карте это не «мягкий край», а грязная рама:
    /// на дневных снимках она съедала десятую часть кадра с каждой стороны и
    /// читалась как поломка экрана.
    static var edgeFade: Color {
        daylight ? groundTone.color : .black
    }

    /// Створ камеры: куда она смотрит. Полупрозрачный и холодный — он даёт
    /// направление, но не спорит за внимание с самой камерой и с дорогой.
    static let cameraGaze = Color(red: 0.35, green: 0.62, blue: 0.78).opacity(0.16)
    /// У тревожной — теплее и заметнее: это уже не контекст, а предупреждение.
    static let cameraGazeAlert = Color(red: 1.0, green: 0.42, blue: 0.42).opacity(0.22)

    /// Рельсы — штрих-пунктир: узнаваемая пиктограмма, а не просто линия.
    static var railTone: Tone { pick(Tone(0.42, 0.40, 0.36),
                                     Tone(0.524, 0.506, 0.477)) }
    static var rail: Color { railTone.color }

    // MARK: - Полотно

    /// Кайма дороги. ТЕМНЕЕ и земли, и полотна в обеих темах: так полотно
    /// читается лежащим на земле, а соседние полосы разделяются даже там, где
    /// они вплотную. Днём кайма — единственное, что отделяет белую дорогу от
    /// светлой земли, поэтому её контраст к полотну задан числом: 2,05.
    static var casingTone: Tone { pick(Tone(0.00, 0.01, 0.02),
                                       Tone(0.680, 0.673, 0.658)) }
    static var casing: Color { casingTone.color }

    /// Асфальт по классу дороги.
    ///
    /// Ночью крупные дороги светлее и чуть теплее, дворы холоднее и темнее.
    /// Днём — та же лестница, но целиком в светлой половине: магистраль почти
    /// белая, дворовый проезд сероватый. Ступени между соседними классами
    /// малы в обеих темах, и это осознанно: иерархию классов на схеме несёт
    /// ШИРИНА, а тон только поддерживает её.
    static func asphaltTone(_ kind: RoadClass) -> Tone {
        if daylight {
            switch kind {
            case .motorway, .trunk:     return Tone(1.000, 0.996, 0.984)
            case .primary:              return Tone(0.995, 0.991, 0.980)
            case .secondary:            return Tone(0.983, 0.979, 0.967)
            case .tertiary:             return Tone(0.970, 0.966, 0.954)
            case .residential:          return Tone(0.957, 0.953, 0.941)
            case .service:              return Tone(0.940, 0.936, 0.925)
            case .pedestrian, .unknown: return Tone(0.923, 0.919, 0.908)
            }
        }
        switch kind {
        case .motorway, .trunk:     return Tone(0.42, 0.41, 0.38)
        case .primary:              return Tone(0.37, 0.36, 0.34)
        case .secondary:            return Tone(0.32, 0.32, 0.32)
        case .tertiary:             return Tone(0.27, 0.27, 0.28)
        case .residential:          return Tone(0.22, 0.22, 0.24)
        case .service:              return Tone(0.18, 0.18, 0.20)
        case .pedestrian, .unknown: return Tone(0.16, 0.17, 0.19)
        }
    }
    static func asphalt(_ kind: RoadClass) -> Color { asphaltTone(kind).color }

    /// Источник, который класса НЕ ЗНАЕТ (индекс лимитов), получает один
    /// средний тон на всё. Рисовать «магистраль» по догадке нельзя — здесь
    /// это так же недопустимо, как в оповещениях.
    static var asphaltUnknownTone: Tone { pick(Tone(0.28, 0.28, 0.29),
                                               Tone(0.963, 0.959, 0.948)) }
    static var asphaltUnknown: Color { asphaltUnknownTone.color }

    /// Тоннель — «под землёй»: заметно глуше всего остального.
    static var asphaltTunnelTone: Tone { pick(Tone(0.13, 0.13, 0.15),
                                              Tone(0.796, 0.793, 0.788)) }
    static var asphaltTunnel: Color { asphaltTunnelTone.color }

    /// Осевая разметка. Только на крупных дорогах: на дворовом проезде её нет
    /// и в жизни, а нарисованная — это выдуманная деталь.
    ///
    /// Днём разметка ТЕМНЕЕ полотна, ночью светлее его: белая краска на белом
    /// асфальте исчезает, и меняется не яркость, а сторона контраста.
    static var centerlineTone: Tone { pick(Tone(0.88, 0.85, 0.72),
                                           Tone(0.741, 0.734, 0.715)) }
    static var centerline: Color {
        daylight ? centerlineTone.color : centerlineTone.color(0.30)
    }

    /// Разделительная между полосами. Бледнее осевой, и это не оттенок, а
    /// иерархия: осевая делит ВСТРЕЧНЫЕ потоки — её пересекать нельзя;
    /// разделительная делит попутные — её пересекают каждым перестроением.
    static var laneDividerTone: Tone { pick(Tone(0.88, 0.85, 0.72),
                                            Tone(0.831, 0.823, 0.802)) }
    static var laneDivider: Color {
        daylight ? laneDividerTone.color : laneDividerTone.color(0.16)
    }

    /// Краска на асфальте: зебра и стоп-линия. ЯРЧЕ и осевой, и
    /// разделительных, и это иерархия, а не вкус: линии вдоль дороги
    /// сопровождают движение, а поперечная черта его ОСТАНАВЛИВАЕТ.
    static var markingTone: Tone { pick(Tone(0.94, 0.93, 0.88),
                                        Tone(0.609, 0.603, 0.587)) }
    static var marking: Color {
        daylight ? markingTone.color : markingTone.color(0.62)
    }

    /// Шевроны односторонней.
    static var chevronTone: Tone { pick(Tone(1, 1, 1), Tone(0.723, 0.715, 0.697)) }
    static var chevron: Color {
        daylight ? chevronTone.color(0.85) : chevronTone.color(0.32)
    }

    /// Полотно дороги тревожной камеры и её осевая.
    static var cameraRoad: Color {
        daylight ? Color(red: 0.995, green: 0.985, blue: 0.955)
                 : Color(red: 0.46, green: 0.45, blue: 0.42)
    }
    static var cameraRoadAssumed: Color {
        daylight ? Color(red: 0.905, green: 0.900, blue: 0.888)
                 : Color(red: 0.30, green: 0.30, blue: 0.30)
    }

    /// Трек «откуда я приехал» — самый тихий слой: он объясняет прошлое и не
    /// должен спорить с тем, что впереди.
    static var track: Color {
        daylight ? Color(red: 0.524, green: 0.559, blue: 0.629).opacity(0.5)
                 : Color.white.opacity(0.16)
    }

    // MARK: - Маршрут

    /// Лента маршрута в три слоя: тёмная кайма отделяет её от полотна,
    /// цветное тело — это «куда я еду», светлая жила внутри даёт объём.
    /// Ровно те же три слоя, что у карты машины (см. CarPlayMapView).
    static let routeCasing = Color(red: 0.03, green: 0.07, blue: 0.18)
    /// Один синий маршрут на всех картах (Theme.route). Был зелёный
    /// `success` — «в лимите» и «твой путь» красились одним цветом.
    static let routeBody = Theme.route
    static let routeCore = Color.white.opacity(0.26)

