//  Один арбитр на все реплики за рулём.
//
//  Зачем он появился. Раньше говорили ДВА независимых источника: превышение
//  произносил SpeedLimitService, о камере — AlertPolicy, и друг о друге они не
//  знали. Флаг превышения читался в один момент времени, и если к моменту
//  оповещения о камере водитель сбросил (или флаг дрогнул от шума GPS),
//  камера уходила в тишину: слышно «превысили», не слышно «камера». Ровно это
//  и поймали за рулём — камера в 300–500 метрах молчала.
//
//  Плюс режим «Умно» стоял по умолчанию и означал буквально «молчать о камере,
//  если едешь в лимите». Замысел был верный (голос на каждую камеру в городе
//  превращается в белый шум), исполнение — нет: камера на карте есть, голоса
//  нет, приложение выглядит сломанным. Молчать надо не про камеру, а про то,
//  что о ней нечего добавить: короткая фраза в городе, тук на своей камере.
//
//  Главное правило, которого не было: КАМЕРА ВПЕРЕДИ ПЕРЕБИВАЕТ ПРЕВЫШЕНИЕ.
//  Превышение без камеры — это совет. Камера впереди — это деньги. Говорить
//  надо о втором, и одной фразой, а не двумя внахлёст.
//
//  Чистая логика, вся решаемость — в `decide`; покрыта VoiceDirectorTests.
//

import Foundation

nonisolated enum VoiceDirector {

    /// Всё, что известно на текущем тике. Собирается в одном месте намеренно:
    /// правило «А важнее Б» можно выразить, только когда А и Б видны разом.
    struct Situation: Equatable {
        /// Выбор пользователя: молчать / умно / обо всех.
        var mode: VoiceMode = .smart
        /// Город или трасса (детектор либо ручная фиксация).
        var context: AlertPolicy.Context = .city
        /// Внезапная точка: передвижной радар, тренога, ДТП. Знать о ней
        /// заранее водитель не мог — ради этого оповещения и существуют.
        var isSudden = false
        /// «Своя» камера: проезжаем регулярно и спокойно.
        var isFamiliar = false
        /// Устойчивое превышение в км/ч (nil — не превышаем либо лимит неизвестен).
        var overKmh: Double?
        /// Лимит дороги, если известен или предположен.
        var limitKmh: Int?
        /// Ползём в пробке или на светофоре.
        var isCrawling = false
        /// Первое оповещение об этой камере (второе и третье — эскалация).
        var isFirst = true
    }

    /// Насколько многословно говорить о камере.
    enum Voice: Equatable {
        /// Ни слова. Камеру показывает панель, отмечает тук.
        case none
        /// «Камера, 300 метров» — город, камеры идут одна за другой.
        case brief
        /// «Стационарный радар справа, 500 метров» — трасса, времени много.
        case calm
        /// Полная фраза со скоростью и лимитом плюс сирена и эскалация.
        case urgent
    }

    struct Plan: Equatable {
        var voice: Voice = .none
        /// Сирена по уровням приближения.
        var beeps: Bool { voice == .urgent }
        /// Наращивать сигналы по мере приближения (иначе один тук на входе).
        var escalates: Bool { voice == .urgent }
        /// Короткая фраза вместо полной.
        var isBrief: Bool { voice == .brief }
        /// Добавить к фразе «здесь 60»: на трассе и в срочном режиме — да,
        /// в городе короткой фразой — нет, там дорога каждая доля секунды.
        var speaksLimit = false
        /// Промолчали из-за пробки, но сказать стоит, как поедем.
        var postpone = false

        static let silent = Plan()
    }

    /// Что сказать про камеру впереди.
    ///
    /// Приоритет сверху вниз:
    /// 1. «Молча» — выбор пользователя, он старше всех правил.
    /// 2. Внезапная точка — всегда и срочно.
    /// 3. Устойчивое превышение у камеры — срочно: сейчас будет штраф, и это
    ///    единственная фраза, которую водитель обязан услышать целиком.
    /// 4. Пробка — отсрочка: камера в 300 м сейчас не решение водителя, но
    ///    сказать надо, как только поедем.
    /// 5. Своя камера в городе — только тук: дорога дом→работа проходит одни и
    ///    те же восемь камер дважды в день, и голос на них перестаёт быть
    ///    помощью через две недели. В режиме «обо всех» говорим всё равно.
    /// 6. Иначе: трасса — полная фраза, город — короткая.
    static func decide(_ s: Situation) -> Plan {
        if s.mode == .off { return .silent }
        if s.isSudden { return Plan(voice: .urgent, speaksLimit: s.limitKmh != nil) }
        if let over = s.overKmh, over > 0 {
            return Plan(voice: .urgent, speaksLimit: s.limitKmh != nil)
        }
        if s.isCrawling { return Plan(voice: .none, postpone: true) }
        if s.isFamiliar, s.mode != .always { return .silent }
        return s.context == .highway
            ? Plan(voice: .calm, speaksLimit: s.limitKmh != nil)
            : Plan(voice: .brief)
    }

    /// Говорить ли отдельную фразу про превышение.
    ///
    /// Только когда впереди НЕТ камеры, о которой мы сейчас скажем. Иначе
    /// водитель услышит «Превышение скорости» и следом «Камера, 300 метров» —
    /// две реплики внахлёст, из которых одна обязательно потеряется. Про
    /// камеру фраза и так содержит скорость с лимитом.
    static func announcesOverspeedAlone(cameraAhead: Bool, plan: Plan) -> Bool {
        !(cameraAhead && plan.voice != .none)
    }
}
