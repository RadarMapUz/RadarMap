    /// со 130 до 90 — это метров триста пути и секунд десять, а ещё нужно
    /// оглядеться, кто едет сзади, и перестроиться. Отсюда 29 секунд: на
    /// 110 км/ч — 886 метров, на 130 — 1047. Ровно та просьба, с которой
    /// начался этот разбор: «на трассе не 400 метров, а чуть больше».
    static let alertLeadTimeSeconds: Double = 22
    static let alertLeadTimeHighwaySeconds: Double = 29
