    static let engineMapPitchDegrees: Double = 45

    /// Сколько места движку под кэш тайлов. Это офлайн, а не ускорение:
    /// в поездке по стране связи нет часами.
    static let engineMapCacheBytes = 200 * 1024 * 1024
