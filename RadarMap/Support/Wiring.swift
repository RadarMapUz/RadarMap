//
//  Wiring.swift
//  RadarMap
//
//  Проводка композиционного корня: крючок назначают один раз.
//
//  Сервисы проекта развязаны замыканиями — `onTripFinished`, `onDrivingStart`,
//  `onManeuver` и ещё семь таких же. Все они связываются в одном месте,
//  `AppEnvironment.init`, и CLAUDE.md обещает: чтобы понять, как срабатывает
//  фича, читай этот init.
//
//  У простого замыкания есть свойство, которого нет у списка подписчиков:
//  второе присваивание молча стирает первое. Именно это и случилось —
//  `trip.onTripFinished` назначали дважды подряд, и тринадцать строк недельного
//  дайджеста не выполнялись никогда. Ошибка не проявилась только потому, что
//  второй блок повторял первый слово в слово; правка в первом ушла бы в никуда
//  без единого признака — ни варнинга, ни падения, ни строчки в логе.
//
//  Отсюда проверка. Она ничего не чинит в бою (в релизе `assert` вырезан) —
//  она ловит опечатку проводки на первом же запуске в отладке, там, где её
//  ещё можно прочитать.
//

import Foundation

nonisolated enum Wiring {

    /// Крючок назначают ровно один раз — из `AppEnvironment.init`.
    ///
    /// Зовётся из `didSet`, поэтому получает СТАРОЕ значение: если оно уже было,
    /// значит кто-то перекрыл чужую проводку. Сброс в `nil` разрешён — это
    /// штатное отключение (тесты, разбор сцены), а не потеря обработчика.
    ///
    /// - Parameters:
    ///   - previous: значение до присваивания (`oldValue` из `didSet`).
    ///   - current: значение после — `nil` означает отключение, его пропускаем.
    ///   - name: имя крючка, чтобы сообщение называло виновника.
    static func assertSingleAssignment<T>(previous: T?, current: T?,
                                          _ name: StaticString,
                                          file: StaticString = #fileID,
                                          line: UInt = #line) {
        guard current != nil, previous != nil else { return }
        assertionFailure("""
            крючок \(name) назначен повторно — первое замыкание потеряно молча. \
            Крючок один, и связывать его нужно один раз в AppEnvironment.init: \
            если событию нужны два действия, объедините их в одном замыкании.
            """, file: file, line: line)
    }
}
