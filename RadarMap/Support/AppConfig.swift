    /// нет», когда стрелка дрожит вокруг порога.
    static let alertLeadRampFromKmh: Double = 80
    static let alertLeadRampToKmh: Double = 100
    /// Потолок динамического радиуса (метры).
    ///
    /// Потолок — единственное место, где обещание «предупредим за 29 секунд»
    /// может тихо перестать выполняться: радиус упирается в него, а секунды
    /// после этого падают вместе с ростом скорости, и нигде об этом не сказано.
    ///
    /// 1100 хватало ровно до 137 км/ч. Дальше запас таял: на 160 км/ч — 24.7 с,
