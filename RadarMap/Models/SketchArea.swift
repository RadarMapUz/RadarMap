//
//  SketchArea.swift
//  RadarMap
//
//  Местность под дорогами: вода, зелень, рельсы.
//
//  Зачем отдельный тип, а не ещё один класс дороги. Дорога отвечает на вопрос
//  «где я еду», местность — «что здесь ещё есть». У них разная геометрия
//  (полигон против ленты), разный порядок отрисовки (местность всегда ПОД
//  дорогами) и разная судьба в перегреве. Смешать их в RoadLine значило бы
//  таскать через весь конвейер поле, которое для половины значений не имеет
//  смысла.
//
//  Данные для этого слоя приезжали на сервер всё это время внутри того же
//  .pbf, который качается ради дорог, и выбрасывались фильтром по highway.
//  На тёмной схеме вода — единственный не-серый цвет, и именно она отличает
//  местность от чертежа.
//

import CoreLocation
import Foundation

nonisolated struct SketchArea: Sendable {

    /// Коды — контракт с build_roads.py (AREA_WATER и соседние).
    enum Kind: Int, Sendable, CaseIterable {
        case water = 1
        case green = 2
        case rail = 3
        /// Квартал — грань дорожного графа. Не из OSM: его контур СЛЕДУЕТ из
        /// измеренных дорог, поэтому он честен ровно настолько, насколько
        /// честна сеть.
        case block = 4
        /// Тротуар. Тоже «местность», и это не натяжка: он открытая лента, как
        /// рельсы, и проходит теми же тайлами, той же распаковкой и тем же
        /// бюджетом. Отдельный конвейер ради ленты, ничем не отличающейся от
        /// уже работающей, стоил бы больше, чем экономит.
        case sidewalk = 5
        /// Дом. Последний слой по важности за рулём и первый по числу
        /// объектов: в одном кадре центра Ташкента их 54 094 против семисот
        /// дорог. Показывается только вблизи — там, где водитель уже ищет
        /// подъезд, а не поворот.
        case house = 6
        /// Полотно проезжей части — контур, посчитанный сборкой. Класс дороги
        /// приезжает в старших битах записи, как этажность у дома.
        case road = 7
        /// Площадь перекрёстка: оболочка кромок всех сходящихся дорог.
        case junction = 8
        /// Разделительная полоса между встречными проезжими. Это ЗЕМЛЯ, а не
        /// асфальт: на проспекте потоки разделены газоном или отбойником, и
        /// рисовать там краску значит утверждать, что это разметка.
        case median = 9

        /// Полотно, площадь перекрёстка и разделительная — одна фигура,
        /// разрезанная на записи. Бюджет берёт их одной пачкой: полотно без
        /// перекрёстков это ленты, которые не сходятся.
        var isPavement: Bool {
            self == .road || self == .junction || self == .median
        }

        /// Очередь бюджета: кого рисуем первым, когда мест меньше, чем фигур.
        ///
        /// Отдельное число, а не maxSpanMeters. Тот отвечает на другой вопрос
        /// — «с какого масштаба слой осмыслен», — и взятый ключом бюджета он
        /// ставил воду, зелень и кварталы ВПЕРЕДИ проезжей части: в перегреве
        /// на боевых тайлах 72 места из 120 уходили на местность прежде, чем
        /// рисовалась первая дорога.
        ///
        /// Порядок отвечает на вопрос «что нужно за рулём»: асфальт, потом
        /// форма города, потом ориентиры, и в самом конце — дома и тротуары,
        /// которых по числу больше всего остального вместе.
        var budgetRank: Int {
            switch self {
            case .road:     return 0
            case .junction: return 1
            case .median:   return 2
            case .block:    return 3
            case .water:    return 4
            case .green:    return 5
            case .rail:     return 6
            case .house:    return 7
            case .sidewalk: return 8
            }
        }

        /// До какого охвата слой имеет смысл. Вода, зелень и рельсы — крупные
        /// ориентиры и нужны на любом; кварталы — тоже: именно они дают городу
        /// массу на дальнем плане.
        var maxSpanMeters: Double {
            switch self {
            case .water, .green, .rail: return .greatestFiniteMagnitude
            // Квартал гас после 340 метров — ровно там, где город и должен
            // превращаться в массу застройки, а вместо неё оставалось пустое
            // поле. Их 88 штук в кадре на полкилометра: это дёшево, и это
            // единственное, что отличает город от пустыни на дальнем плане.
            case .block:                return .greatestFiniteMagnitude
            // Тротуар объясняет, где кончается асфальт, — вопрос ближнего
            // плана. Дальше полутора сотен метров он неотличим от кромки
            // дороги, а весит как целый слой: их 3 439 в одном центре.
            case .sidewalk:             return 150
            // Дом отвечает на вопрос последних двухсот метров — «мне вот сюда
            // сворачивать?». На трёхстах он уже не ориентир, а шум, которого
            // по числу объектов больше, чем всей остальной схемы вместе.
            case .house:                return 200
            // Поверхность — вопрос ближнего плана и только его. Дальше двух
            // с половиной сотен метров полотно вырождается в линию, и штрих
            // рисует её и дешевле, и честнее: там уже виден костяк района, а
            // не отдельные проезжие части.
            case .road, .junction:      return 250
            // Разделительная видна там же, где полотно: без него она просто
            // полоса земли посреди земли.
            case .median:               return 250
            }
        }
    }

    var points: [CLLocationCoordinate2D]
    var kind: Kind
    /// Полигон (заливается) против ленты (штрихуется). Река бывает и той, и
    /// другой, рельсы — всегда лента.
    var isClosed: Bool
    /// Этажей у дома. 0 — не сказано, и выдумывать нельзя: одинаковые коробки
    /// по всему городу читаются как макет, а не как город. Замерено: этажность
    /// известна у 40 % домов центра.
    var levels: Int = 0
    /// Класс дороги у полотна. 0 — не полотно или класс не сказан.
    ///
    /// Едет в тех же старших битах, что этажность у дома: пятый элемент записи
    /// невозможен — RoadTiles.decodeEntries принимает длину 3 или 4 и на пятом
    /// возвращает nil на ВЕСЬ тайл.
    var roadClass: Int = 0
}

// CLLocationCoordinate2D не Equatable — сравниваем по координатам сами, как и
// весь остальной геометрический код проекта.
extension SketchArea: Equatable {
    static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.kind == rhs.kind && lhs.isClosed == rhs.isClosed
            && lhs.levels == rhs.levels && lhs.roadClass == rhs.roadClass
            && lhs.points.count == rhs.points.count
            && zip(lhs.points, rhs.points).allSatisfy {
                $0.latitude == $1.latitude && $0.longitude == $1.longitude
            }
    }
}
