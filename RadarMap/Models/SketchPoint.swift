//
//  SketchPoint.swift
//  RadarMap
//
//  Точечные объекты схемы: светофор, лежачий полицейский, стоп-линия, разворот.
//
//  Это ПЕРВЫЙ слой, который приходит не из OSM, а нарисован руками в панели.
//  Отсюда два правила, которых нет у остального:
//
//  • Такие данные не с чем сверить. Дорогу можно сравнить с чужой картой, а
//    светофор, поставленный человеком, подтверждается только этим человеком.
//    Поэтому вид объекта, которого приложение не знает, НЕ рисуется — но и не
//    роняет тайл: сервер вправе завести новый вид раньше, чем выйдет сборка.
//
//  • Виден такой объект только вблизи. На охвате района светофор — точка в
//    один пиксель среди сотни таких же, то есть шум; на ближнем плане это
//    ориентир, по которому водитель понимает, где он.
//

import CoreLocation

nonisolated struct SketchPoint: Sendable {

    /// Коды — контракт с build_roads.py (POINT_TRAFFIC_LIGHT и соседние).
    enum Kind: Int, Sendable, CaseIterable {
        case trafficLight = 1
        case speedBump = 2
        case stopLine = 3
        case uTurn = 4

        /// До какого охвата объект имеет смысл.
        ///
        /// Граница НЕ на вкус, а по геометрии: дальше farNetworkSpan схема
        /// рисует не улицы, а костяк района — раздельные проезжие части там
        /// сведены в одну ось, то есть линия проходит МЕЖДУ ними. Точка
        /// посажена сервером на детальную геометрию, и на костяке она уехала
        /// бы от нарисованной дороги на полширины проспекта.
        ///
        /// Плотность на этой границе замерена: в самом плотном кадре центра
        /// Ташкента 7 пиктограмм на охвате 260 м и 9 на 340 — то есть предел
        /// ставит геометрия, а не теснота.
        ///
        /// Светофор — исключение: для него сервер считает ВТОРОЙ набор, по
        /// костяку района, поэтому он живёт до самого дальнего охвата. Так и
        /// надо: на охвате района светофоры — это и есть карта перекрёстков,
        /// по ней читается, где город, а где проезд насквозь.
        var maxSpanMeters: Double {
            self == .trafficLight ? RoadSketch.maxSpanMeters : RoadSketch.farNetworkSpan
        }
    }

    var coordinate: CLLocationCoordinate2D
    var kind: Kind
}

extension SketchPoint: Equatable {
    static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.kind == rhs.kind
            && lhs.coordinate.latitude == rhs.coordinate.latitude
            && lhs.coordinate.longitude == rhs.coordinate.longitude
    }
}
