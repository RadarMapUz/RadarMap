//
//  TickPacing.swift
//  RadarMap
//
//  Ритм анимаций, привязанных к GPS-тикам. Одно правило на всех.
//
//  Плавность движущейся картинки — это не частота кадров, а РИТМ ключевых
//  кадров: анимация обязана длиться ровно до следующего ожидаемого фикса.
//  С жёсткой константой (вью «красиво» анимирует 0.4–1 с, а фикс приходит
//  через 2–3 с) картинка едет и замирает — ровно так дёргалась схема
//  приборки, и ровно так же шагала большая карта в режиме следования.
//
//  Лучшее предсказание следующего интервала — предыдущий: адаптивный GPS
//  меняет частоту плавно (тиры с гистерезисом), и ошибка предсказания —
//  доли секунды, которые глаз не читает.
//
//  Родился в RoadSketch; вынесен, когда тем же правилом зажило ведение
//  большой карты. Держать две копии значило чинить рывки дважды.
//

import Foundation

nonisolated enum TickPacing {

    /// Длительность анимации до следующего ожидаемого тика.
    ///
    /// Зажим сверху: после паузы (светофор, туннель, потеря сигнала) догонять
    /// точку три секунды можно, дольше — уже враньё о том, где мы. Снизу —
    /// защита от дребезга, когда два фикса пришли почти одновременно.
    static func animationDuration(sincePreviousTick dt: TimeInterval?) -> TimeInterval {
        min(max(dt ?? 1, 0.35), 3.0)
    }
}
