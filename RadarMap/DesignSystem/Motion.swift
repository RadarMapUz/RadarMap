//  «Уменьшение движения» — системная настройка, которую приложение не замечало.
//
//  Замер: в коде около 120 мест с `withAnimation` и `.animation(_:value:)` и
//  РОВНО ОДНА проверка `UIAccessibility.isReduceMotionEnabled` — в камере
//  движка карты. Всё остальное анимировалось всегда: каскад появления карточек
//  в Итогах, тридцать три анимации главного экрана, полуторасекундный пролёт
//  карты на экране проезда.
//
//  Почему это не косметика. Человек, включивший эту настройку, просит об этом
//  не из вкуса: движущийся интерфейс вызывает у него тошноту и головокружение
//  (вестибулярные расстройства, мигрень). В машине к этому добавляется
//  собственное движение автомобиля — и экран, который качается сам по себе,
//  становится источником укачивания для пассажира.
//
//  Почему обёртки, а не проверка на месте. Проверка на месте — это сто двадцать
//  мест, где её можно забыть, и сто двадцать первое, где её забудут. Обёртки
//  называются почти как оригиналы, читаются так же и не оставляют выбора:
//  `withAnimation` в этом проекте просто не используется.
//
//  Чистое правило — покрыто MotionTests.
//

import SwiftUI
#if canImport(UIKit)
import UIKit
#endif

enum Motion {

    /// Система просит не двигать интерфейс.
    ///
    /// Читается напрямую, без кэша — в отличие от коэффициента кегля
    /// (`Font.rawTypeFactor`), где кэш появился не от осторожности, а потому
    /// что `UIFontMetrics.scaledValue` считает разметку. Здесь за флагом стоит
    /// готовое булево значение настройки доступности, и заводить вокруг него
    /// кэш с подпиской на уведомление значит усложнять там, где нечего
    /// экономить.
    static var isReduced: Bool {
        #if canImport(UIKit)
        UIAccessibility.isReduceMotionEnabled
        #else
        false
        #endif
    }

    /// Анимация с учётом настройки. `nil` — SwiftUI применит изменение
    /// мгновенно; это именно то, о чём просили, а не «анимация покороче».
    ///
    /// Сокращать длительность вместо отключения — частая и неверная уступка:
    /// быстрое движение укачивает не меньше медленного, а иногда сильнее.
    static func ok(_ animation: Animation?) -> Animation? {
        isReduced ? nil : animation
    }
}

/// Замена `withAnimation`, уважающая «Уменьшение движения».
///
/// Имя отличается одним словом намеренно: так замена механическая, а забытое
/// место видно поиском по `withAnimation` — его в проекте быть не должно.
@MainActor
func withMotion<Result>(_ animation: Animation? = .default,
                        _ body: () throws -> Result) rethrows -> Result {
    try withAnimation(Motion.ok(animation), body)
}

extension View {
    /// Замена `.animation(_:value:)`, уважающая «Уменьшение движения».
    func motionAnimation<V: Equatable>(_ animation: Animation?, value: V) -> some View {
        self.animation(Motion.ok(animation), value: value)
    }
}
