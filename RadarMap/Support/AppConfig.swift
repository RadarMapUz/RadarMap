    ///
    /// Потолок ничего не ломает на кривых: коридор пересчитывается на каждом
    /// фиксе, а `Decision.isFirst` даёт полноценный голос и поздно замеченной
    /// камере. Худшее следствие — на сильно изогнутой трассе о камере скажут
    /// не за 29 секунд, а за 20, когда дорога довернёт. Лучшее — молчание про
    /// камеру на встречном шоссе за разделительной.
    nonisolated static let corridorCityMaxMeters: CLLocationDistance = 90
    nonisolated static let corridorHighwayMaxMeters: CLLocationDistance = 140
    /// Погрешность НАШЕЙ точки, на которую ширины коридора выше уже
    /// рассчитаны (`corridorMinNearMeters`: «точность ограничена GPS»): та же
    /// база, что у куска дороги (`roadShapeMinToleranceMeters`, отличный GPS).
    /// Сверх неё каждый метр погрешности расширяет коридор на
    /// `corridorAccuracyFactor` метров (14.14).
    ///
    /// Коридор мерится от линии курса через нашу точку, а в каньоне портится
    /// именно точка: доплеровский курс остаётся уверенным (LocationFilter
    /// ему верит), а фикс в 25–65 м уезжает вбок на десятки метров — и
    /// держится там, отражение сдвигает в одну сторону. Узкий коридор
    /// доказанных сторон (18 м) и городской (30 м) выталкивали свою камеру с
