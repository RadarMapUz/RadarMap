    /// вовсе.
    nonisolated static let corridorAccuracyBaselineMeters: CLLocationAccuracy = roadShapeMinToleranceMeters
    /// Метров допуска на метр погрешности сверх базы. Один к одному — как у
    /// куска дороги (там допуск `max(10 м, точность)`): точка, ушедшая вбок
    /// на свою заявленную погрешность, сдвигает линию курса ровно на столько
    /// же, и своя камера остаётся в коридоре с прежним запасом ширины.
    /// Погрешность — радиус, а не граница: ушедший дальше заявленного фикс
    /// выпадает на тик, как и хороший, — без прибавки это был весь подъезд.
    ///
    /// Прибавка идёт ПОВЕРХ потолка: потолок ограничивает изгиб дороги, а не
    /// неуверенность в собственной точке. Граница честная: в городе на худшем
    /// принятом фиксе (`maxHorizontalAccuracyMeters`, 65 м) коридор не шире
    /// 90 + 55 = 145 м — улица в 150 м вбок не наша ни на каком фиксе. На
