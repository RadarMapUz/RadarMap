//
//  CarPlayRootWatch.swift
//  RadarMap
//
//  Показан ли корневой шаблон на экране машины — и что делать, если
//  система об этом промолчала.
//
//  До 2.2.14 единственным признаком был templateDidAppear у корня, и от него
//  зависело всё, что требует шаблона на экране: навигационная сессия
//  (карточка манёвра, полосы, камеры поверх чужого приложения) и алерт о
//  разрешении. Журналы 12.10 (carplay4, carplay10) показали, что система
//  этот вызов для корня присылает НЕ всегда: машина подключилась, когда
//  сцена ещё не была на экране, корень поставлен, сцена вышла вперёд — а
//  templateDidAppear так и не пришёл. Сессия не начиналась до конца
//  подключения, а сторож каждые 3 с после возврата в приложение ставил корень
//  заново (и сбрасывал всё, что было поверх него).
//
//  Правило: корень, установку которого система подтвердила (completion без
//  ошибки), считается показанным, когда сцена активна и прошла пауза на
//  анимацию. Ставить его заново имеет смысл, только если установка не
//  подтверждена, — и не больше одного раза за подключение. Чистая логика,
//  покрыто CarPlayRootWatchTests.
//

import Foundation

nonisolated enum CarPlayRootWatch {

    enum Action: Equatable, Sendable {
        /// Ничего не делать: корень уже показан или повтор уже был.
        case none
        /// Считать корень показанным: начать сессию, спросить разрешение.
        case markShown
        /// Установить корень ещё раз.
        case setAgain
    }

    /// Что делать при проверке, когда сцена машины активна.
    /// - Parameters:
    ///   - rootShown: templateDidAppear у корня уже был (или корень уже признан).
    ///   - rootSet: ответ системы на setRootTemplate — nil, пока его нет;
    ///     true — установлен; false — ошибка.
    ///   - retried: корень в этом подключении уже ставили повторно.
    ///   - timedOut: прошло carPlayTemplateShowTimeout; до этого неподтверждённую
    ///     установку ещё ждём, а не повторяем.
    static func action(rootShown: Bool, rootSet: Bool?, retried: Bool, timedOut: Bool) -> Action {
        if rootShown { return .none }
        if rootSet == true { return .markShown }
        guard timedOut, !retried else { return .none }
        return .setAgain
    }
}
